// rebuild must fold onto the root it is given, never the root compiled
// into the generator: a CLDR release that changes root would otherwise
// be checked against the previous generation and pass.
func TestRebuildUsesTheGivenRoot(t *testing.T) {
	fresh := locales.Locale{Minus: "−", Standard: "¤#,##0.00", Symbols: map[string]string{"USD": "US$"}}
	byID := map[string]locales.Locale{
		"xx":    {Parent: "root", Standard: "#,##0.00 ¤"},
		"xx-YY": {Parent: "xx", Symbols: map[string]string{"USD": "$"}},
	}
	got := rebuild("xx-YY", byID, fresh)
	if got.Minus != "−" || got.Standard != "#,##0.00 ¤" || got.Symbols["USD"] != "$" {
		t.Errorf("rebuild = %+v; want the given root's minus, xx's pattern and xx-YY's symbol", got)
	}
	if fresh.Symbols["USD"] != "US$" {
		t.Error("rebuild changed the root it was given")
	}
}

// A language CLDR drops from the modern set must leave the tree: left
// behind, its pack still compiles, and an app can import data no run of
// the generator vouches for. Only files the generator wrote are
// removed, and a directory only once it is empty.
func TestPruneStaleRemovesOnlyGeneratedOrphans(t *testing.T) {
	dir := t.TempDir()
	gen := "// Code generated by cmd/gen; DO NOT EDIT.\n\npackage x\n"
	files := map[string]string{
		"de/pack_gen.go":       gen,                                // written this run
		"modern/modern_gen.go": gen,                                // written this run
		"xx/pack_gen.go":       gen,                                // orphan: goes, with its directory
		"yy/pack_gen.go":       gen,                                // orphan beside a hand-written file
		"yy/notes.go":          "package yy\n",                     // not the generator's
		"zz/pack_gen.go":       "// written by hand\npackage zz\n", // not the generator's
		"core_gen.go":          gen,
	}
	for name, body := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	pruneStale(dir, map[string]bool{"de": true, "modern": true})
	for name, want := range map[string]bool{
		"de/pack_gen.go": true, "modern/modern_gen.go": true, "core_gen.go": true,
		"xx": false, "yy/pack_gen.go": false, "yy/notes.go": true, "zz/pack_gen.go": true,
	} {
		if _, err := os.Stat(filepath.Join(dir, name)); (err == nil) != want {
			t.Errorf("%s: exists = %v, want %v", name, err == nil, want)
		}
	}
}
