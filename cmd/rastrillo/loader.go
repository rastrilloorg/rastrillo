// The throwaway program rastrillo writes into an app to ask it
// questions only its own packages can answer.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// loaderDir is the throwaway package `loadPayload` writes into the
// app module. No leading dot or underscore: the go tool skips
// directories named that way, so `go run ./loaderDir` would silently
// find nothing to run.
const loaderDir = "rastrillo_migration_dump"

const loaderTemplate = `// Code generated by rastrillo; removed right after use.
package main

import (
	app %q

	"amadan.net/rastrillo/rastrillo/migrate/dump"
)

func main() { %s }
`

// loaderCall is a loader's main body and the package-level names it
// reads off the app, which are also what finds the app's package: a
// command must not need names its call never reads.
type loaderCall struct {
	body  string
	needs []string
}

// payloadCall is the loader's body for the migration subcommands.
var payloadCall = loaderCall{
	body: "dump.Main(app.Schema.All(), " +
		"app.BootSchema.All(), app.Models)",
	needs: migrationNeeds,
}

// runLoader writes a loader program whose main is call's body, runs it
// in the app module, and decodes the JSON it prints into into. The
// audit subcommands share it so only the call differs.
func runLoader(dir, override string, call loaderCall, into any) error {
	importPath, _, err := appPackage(dir, override, call.needs)
	if err != nil {
		return err
	}
	ldir := filepath.Join(dir, loaderDir)
	if err := os.MkdirAll(ldir, 0o755); err != nil {
		return err
	}
	defer os.RemoveAll(ldir)

	body := fmt.Sprintf(loaderTemplate, importPath, call.body)
	mainFile := filepath.Join(ldir, "main.go")
	if err := os.WriteFile(mainFile, []byte(body), 0o644); err != nil {
		return err
	}

	cmd := exec.Command("go", "run", "./"+loaderDir)
	cmd.Dir = dir
	var stderr strings.Builder
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		// The compiler's own message is the only thing a developer
		// sees when their app doesn't build — wrapping it in a
		// generic "loader failed" would send them hunting for a bug
		// in rastrillo instead of the app.
		return fmt.Errorf("loading the app's models failed — "+
			"the app must compile:\n%s", stderr.String())
	}
	if err := json.Unmarshal(out, into); err != nil {
		return fmt.Errorf("could not parse the loader's output: %w", err)
	}
	return nil
}
