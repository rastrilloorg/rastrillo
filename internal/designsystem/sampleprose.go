// sampleProse is the samples' words in the eleven other languages: the
// labels, buttons, headings, hints, row titles and status words the
// components are shown holding. localise.go says which strings are
// looked up and which stay as written; this is only the table.
//
// It is kept apart from prose.go because the two are different kinds of
// copy. prose is the page explaining itself; this is the stand-in
// content of an imaginary app, and a translator reviewing one wants the
// other out of the way. They are one table at run time, merged below,
// so proseIn, the parity gate and the leak gate need no second path.
//
// Machine-drafted, in the register of the base catalogs: short, plain,
// the words an app in that language would actually put on a button. The
// strings the framework's own catalog already says (a URL field's
// error, a date range's) carry the catalog's translation, so a sample
// does not word the same message two ways. Names, addresses, brands and
// codes inside a sentence are kept as written;
// TestSampleTranslationsKeepTheirStandIns holds that.
//
// A key may carry markup: a sentence whose numbers sit in <strong>, or
// whose link sits in an <a>, is translated whole so the language can put
// them where its grammar wants them. TestSampleMarkupSurvivesTranslation
// holds every translation to the same elements and machine attributes
// as its key.
