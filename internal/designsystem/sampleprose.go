// The merge refuses a key prose.go already has. Two entries for one
// English string would leave which translation wins to map order, and
// the page and the samples saying the same word two ways is exactly
// what sharing the table is for.
func init() {
	for k, v := range sampleProse {
		if _, dup := prose[k]; dup {
			panic("designsystem: sampleprose.go and prose.go both translate " + k)
		}
		prose[k] = v
	}
}
