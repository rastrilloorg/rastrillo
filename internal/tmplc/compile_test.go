const pkgPath = "example.com/app/web"

// input is what tmplgen would hand Compile for one set holding these
// templates. A template's fingerprint is the hash of its name alone, so
// a test can look for it.
func input(t *testing.T, sources map[string]string) tmplc.Input {
	t.Helper()
	set := tmpl.CapturedSet{
		Name:         "app",
		Owner:        pkgPath,
		Templates:    sources,
		Fingerprints: map[string]string{},
		Funcs:        map[string]tmpl.FuncSig{},
		Option:       "default",
		Uncompilable: map[string]string{},
	}
	trees := map[string]*parse.Tree{}
	for name, src := range sources {
		tree := parse.New(name)
		tree.Mode = parse.SkipFuncCheck
		_, err := tree.Parse(src, "", "", map[string]*parse.Tree{})
		if err != nil {
			t.Fatal(err)
		}
		trees[name] = tree
		set.Fingerprints[name] = fmt.Sprintf("%x", sha256.Sum256([]byte(name)))
	}
	return tmplc.Input{
		PkgPath: pkgPath,
		PkgName: "web",
		Sets:    []tmpl.CapturedSet{set},
		Escaped: []map[string]tmplescape.Result{
			tmplescape.EscapeAll(
				trees,
				tmplescape.Options{MetaContentURLEscape: true},
			),
		},
	}
}

func TestUnsupportedPropagates(t *testing.T) {
	in := input(t, map[string]string{
		"inner": `<i>{{print ($x := .X)}}</i>`,
		"outer": `<p>{{template "inner" .}}</p>`,
		"other": `<b title="{{.Name}}">{{.Name}}</b>`,
	})
	out, err := tmplc.Compile(in)
	if err != nil {
		t.Fatal(err)
	}
	reasons := map[string]string{}
	for _, note := range out.Unsupported {
		if note.Owner != pkgPath || note.Set != "app" {
			t.Errorf("note %+v: want owner %q and set %q", note, pkgPath, "app")
		}
		reasons[note.Template] = note.Reason
	}
	if !strings.Contains(reasons["inner"], "parentheses") {
		t.Errorf(
			"inner: reason %q does not say what is unsupported",
			reasons["inner"],
		)
	}
	if !strings.Contains(reasons["outer"], `"inner"`) {
		t.Errorf(
			"outer: reason %q does not name the template it calls",
			reasons["outer"],
		)
	}
	if reason, ok := reasons["other"]; ok {
		t.Errorf("other was reported unsupported: %s", reason)
	}

	src := string(out.Source)
	other := in.Sets[0].Fingerprints["other"]
	if !strings.Contains(src, `tmplrt.Register("`+other+`"`) {
		t.Errorf("other's fingerprint %s is not registered:\n%s", other, src)
	}
	for _, name := range []string{"inner", "outer"} {
		if fp := in.Sets[0].Fingerprints[name]; strings.Contains(
			src,
			`tmplrt.Register("`+fp,
		) {
			t.Errorf("%s's fingerprint %s is registered", name, fp)
		}
	}
	// Every template without code is listed by fingerprint, or the
	// runtime would call the code stale.
	want := registerOwner(pkgPath, in.Sets[0], "inner", "outer")
	if !strings.Contains(src, want) {
		t.Errorf(
			"RegisterOwner does not list inner and outer, want %s:\n%s",
			want,
			src,
		)
	}
}

func TestGeneratedFileShape(t *testing.T) {
	in := input(t, map[string]string{
		"list": `{{if .Items}}<ul>{{range .Items}}<li>{{.}}</li>{{end}}</ul>` +
			`{{else}}none{{end}}`,
		"link": `<a href="{{.URL}}">{{.Owner.Name}}</a>`,
	})
	out, err := tmplc.Compile(in)
	if err != nil {
		t.Fatal(err)
	}
	if len(out.Unsupported) > 0 {
		t.Fatalf("unsupported: %+v", out.Unsupported)
	}
	// The lint line keeps staticcheck's SA4 checks, which flag code
	// that does nothing, off the template logic the file spells out:
	// {{eq .A .A}} compares a value with itself, and {{range}}{{break}}
	// is a loop that always exits. The app's staticcheck must pass on it.
	// The build line leaves the file out of capture, so a stale one
	// cannot block its own regeneration, and out of rastrillo dev, so a
	// renamed field cannot break edit and refresh.
	want := "// Code generated by rastrillo generate; DO NOT EDIT.\n\n" +
		"//go:build !rastrillo_capture && !rastrillo_dev\n\n" +
		"//lint:file-ignore SA4* this file spells out the templates' " +
		"own logic, which may compare a value with itself or leave " +
		"a loop at once\n\npackage web\n"
	if !bytes.HasPrefix(out.Source, []byte(want)) {
		t.Fatalf(
			"source starts\n%s\nwant\n%s",
			out.Source[:min(len(out.Source), len(want))],
			want,
		)
	}
	_, err = parser.ParseFile(token.NewFileSet(), "gen.go", out.Source, 0)
	if err != nil {
		t.Fatalf("generated source does not parse: %v\n%s", err, out.Source)
	}
	count := strings.Count(string(out.Source), "tmplrt.RegisterOwner(")
	if count != 1 {
		t.Errorf("RegisterOwner called %d times, want once", count)
	}

	// Map order must not leak into the file: the freshness check
	// compares bytes.
	for range 5 {
		again, err := tmplc.Compile(input(t, in.Sets[0].Templates))
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(again.Source, out.Source) {
			t.Fatal("two compiles of the same input differ")
		}
	}
}

// TestSharedBodiesAreEmittedOnce compiles two sets that hold the same
// template, as a clone does, and a template that differs only in name:
// each fingerprint is registered once, and equal bodies are one
// function.
func TestSharedBodiesAreEmittedOnce(t *testing.T) {
	in := input(t, map[string]string{"a": `<p>{{.}}</p>`})
	clone := input(t, map[string]string{"a": `<p>{{.}}</p>`})
	in.Sets = append(in.Sets, clone.Sets...)
	in.Escaped = append(in.Escaped, clone.Escaped...)
	out, err := tmplc.Compile(in)
	if err != nil {
		t.Fatal(err)
	}
	src := string(out.Source)
	if count := strings.Count(src, "tmplrt.Register("); count != 1 {
		t.Errorf(
			"%d registrations for one fingerprint, want 1:\n%s",
			count,
			src,
		)
	}
	if count := strings.Count(src, "\nfunc exec_"); count != 1 {
		t.Errorf("%d bodies for one template, want 1:\n%s", count, src)
	}
}

func TestEscapeErrorIsReported(t *testing.T) {
	// html/template refuses an action that ends inside a tag's attribute
	// name differently on each branch.
	in := input(t, map[string]string{"bad": `<a {{if .}}href{{end}}="x">`})
	out, err := tmplc.Compile(in)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.ContainsFunc(
		out.Unsupported,
		func(note tmplc.Note) bool { return note.Template == "bad" },
	) {
		t.Errorf("escape error not reported: %+v", out.Unsupported)
	}
	if want := registerOwner(pkgPath, in.Sets[0], "bad"); !strings.Contains(
		string(out.Source),
		want,
	) {
		t.Errorf(
			"bad is not listed as left on html/template, want %s:\n%s",
			want,
			out.Source,
		)
	}
}

// TestCloneSourceEscapeErrorIsQuiet: a set the app clones, as
// ui.NewPages clones its base, may call a template only its clones
// define. It is not reported, but its fingerprint is still left out.
func TestCloneSourceEscapeErrorIsQuiet(t *testing.T) {
	in := input(
		t,
		map[string]string{"layout": `<main>{{template "content" .}}</main>`},
	)
	in.Sets[0].Cloned = true
	out, err := tmplc.Compile(in)
	if err != nil {
		t.Fatal(err)
	}
	if len(out.Unsupported) > 0 {
		t.Errorf(
			"a clone source's escape error was reported: %+v",
			out.Unsupported,
		)
	}
	if want := registerOwner(pkgPath, in.Sets[0], "layout"); !strings.Contains(
		string(out.Source),
		want,
	) {
		t.Errorf(
			"layout is not listed as left on html/template, want %s:\n%s",
			want,
			out.Source,
		)
	}
}

// registerOwner is the RegisterOwner call that leaves names of set out.
func registerOwner(owner string, set tmpl.CapturedSet, names ...string) string {
	var fps []string
	for _, name := range names {
		fps = append(fps, strconv.Quote(set.Fingerprints[name]))
	}
	slices.Sort(fps)
	return fmt.Sprintf(
		"tmplrt.RegisterOwner(%q, []string{%s})",
		owner,
		strings.Join(fps, ", "),
	)
}

// TestMainPackageRegistersAsMain: tmpl records a set built in a main
// package under the owner "main", which is how the runtime names its
// functions, so that is the owner the stale check asks about.
func TestMainPackageRegistersAsMain(t *testing.T) {
	in := input(
		t,
		map[string]string{"home": `<p>{{.}}</p>`, "odd": `{{print ($x := .)}}`},
	)
	in.PkgPath, in.PkgName = "example.com/app/cmd/app", "main"
	out, err := tmplc.Compile(in)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(
		string(out.Source),
		registerOwner("main", in.Sets[0], "odd"),
	) {
		t.Errorf("owner not registered as main:\n%s", out.Source)
	}
	if len(out.Unsupported) != 1 || out.Unsupported[0].Owner != in.PkgPath {
		t.Errorf("notes %+v: want one, naming %s", out.Unsupported, in.PkgPath)
	}
}
