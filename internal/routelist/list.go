package routelist

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"amadan.net/rastrillo/rastrillo/action"
)

// programDir is where the listing program appears inside the module.
// It exists only in the build's overlay, never on disk; the leading dot
// keeps ./... from matching it if it ever did.
const programDir = ".rastrillo-routes"

// program calls Routes with a recorder and an empty dependency, and
// writes the table to the file named by its one argument. Not stdout:
// the app may print there, and what it prints must not be taken for
// routes.
const program = `// Code generated by rastrillo routes. DO NOT EDIT.

package main

import (
	"encoding/json"
	"fmt"
	"os"

	"amadan.net/rastrillo/rastrillo/action"
	routed %q
)

func main() {
	var app routed.%s
	routes := action.NewRecorder()
	routed.Routes(routes, %sapp)
	listing, err := json.Marshal(routes.List())
	if err == nil {
		err = os.WriteFile(os.Args[1], listing, 0o600)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
`

// List builds a program inside the app's module, without writing
// there, runs it, and reads the routes it recorded. Whatever happens,
// the scratch directory is removed and no process it started is left.
// The caller cancels ctx on SIGINT and SIGTERM (signal.NotifyContext):
// the children are in a group of their own, which a Ctrl-C does not
// reach, and a signal left to kill this process skips the cleanup.
func List(ctx context.Context, target Target) ([]action.Route, error) {
	if err := keptFree(target); err != nil {
		return nil, err
	}
	modFlag, err := goSettings(ctx, target.ModuleDir)
	if err != nil {
		return nil, err
	}
	scratch, err := os.MkdirTemp("", "rastrillo-routes-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(scratch)
	binary, err := build(ctx, target, scratch, modFlag)
	if err != nil {
		return nil, err
	}
	listing := filepath.Join(scratch, "routes.json")
	runner := inOwnGroup(ctx, binary, listing)
	runner.Stdout = appOutput(target.Output)
	runner.Stderr = runner.Stdout
	if err := runner.run(); err != nil {
		if ctx.Err() != nil {
			return nil, stopped{stoppedBeforeListing, ctx.Err()}
		}
		return nil, say(runFailed, err, target.AppType)
	}
	return readListing(listing)
}

// keptFree refuses an app with something of its own at programDir. The
// overlay replaces only main.go, so every other Go file in a real
// directory there would be compiled into the program and run.
func keptFree(target Target) error {
	own := filepath.Join(target.ModuleDir, programDir)
	if _, err := os.Lstat(own); err == nil {
		return say(reservedDirectory, own)
	}
	return nil
}

// build compiles the program with modFlag, goSettings' -mod=readonly
// or -mod=vendor, so go.mod and go.sum stay as they are, and with the
// go command's own scratch inside ours: go build leaves its work
// directory behind when it is killed, even by SIGINT, so only removing
// ours removes it.
func build(
	ctx context.Context, target Target, scratch, modFlag string,
) (string, error) {
	overlay, err := writeOverlay(target, scratch)
	if err != nil {
		return "", err
	}
	work := filepath.Join(scratch, "work")
	if err := os.Mkdir(work, 0o700); err != nil {
		return "", err
	}
	binary := filepath.Join(scratch, "routes")
	builder := inOwnGroup(ctx, "go", "build", "-overlay", overlay,
		modFlag, "-buildvcs=false", "-o", binary, "./"+programDir)
	builder.Dir = target.ModuleDir
	// PWD as well as Dir: os/exec sets PWD only when Env is nil, and
	// with a stale PWD the go command resolves ./programDir by the
	// physical path, which is not the overlay's when the module is
	// reached through a symlink.
	builder.Env = append(os.Environ(),
		"GOTMPDIR="+work, "PWD="+target.ModuleDir)
	var reported bytes.Buffer
	builder.Stdout, builder.Stderr = &reported, &reported
	if err := builder.run(); err != nil {
		if ctx.Err() != nil {
			return "", stopped{stoppedBeforeListing, ctx.Err()}
		}
		return "", say(buildFailed,
			strings.TrimSpace(reported.String()))
	}
	return binary, nil
}

// writeOverlay writes the program to scratch and the overlay that
// makes it appear at programDir in the module: a package there may
// import the module's internal packages, and one elsewhere may not.
func writeOverlay(target Target, scratch string) (string, error) {
	pointer := ""
	if target.Pointer {
		pointer = "&"
	}
	source := filepath.Join(scratch, "main.go")
	text := fmt.Sprintf(program, target.ImportPath, target.AppType, pointer)
	if err := os.WriteFile(source, []byte(text), 0o600); err != nil {
		return "", err
	}
	placed := filepath.Join(target.ModuleDir, programDir, "main.go")
	overlay, err := json.Marshal(map[string]map[string]string{
		"Replace": {placed: source},
	})
	if err != nil {
		return "", err
	}
	path := filepath.Join(scratch, "overlay.json")
	return path, os.WriteFile(path, overlay, 0o600)
}

func readListing(path string) ([]action.Route, error) {
	listing, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, say(noListingWritten)
	}
	if err != nil {
		return nil, say(unreadableListing, err)
	}
	var routes []action.Route
	if err := json.Unmarshal(listing, &routes); err != nil {
		return nil, say(unreadableListing, err)
	}
	return routes, nil
}

func appOutput(output io.Writer) io.Writer {
	if output == nil {
		return os.Stderr
	}
	return output
}

// stopped is what a cancelled Find, List or Unmounted returns: the
// person reads that it stopped, and errors.Is still finds the context's
// reason.
type stopped struct {
	message string
	cause   error
}

func (reason stopped) Error() string { return reason.message }

func (reason stopped) Unwrap() error { return reason.cause }
