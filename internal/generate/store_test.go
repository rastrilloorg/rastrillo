func TestEmitStoreFiltersDeduped(t *testing.T) {
	dir := t.TempDir()
	r := filteredFixtureResource()

	if _, err := EmitStore(dir, []rastrillo.Resource{r}); err != nil {
		t.Fatalf("EmitStore: %v", err)
	}

	cases := []struct {
		path string
		want string
	}{
		{filepath.Join(dir, "store", "events", "schema.sql"), goldenEventsSchemaSql},
		{filepath.Join(dir, "store", "events", "queries.sql"), goldenEventsQueriesSql},
	}
	for _, c := range cases {
		got, err := os.ReadFile(c.path)
		if err != nil {
			t.Fatalf("read %s: %v", c.path, err)
		}
		if string(got) != c.want {
			t.Errorf("%s:\ngot:\n%s\nwant:\n%s", c.path, got, c.want)
		}
	}

	// Verify that filter_status appears in both List and Count queries but not duplicated
	// (when Status is in both Filter and Filters, the union should deduplicate it).
	// Each query has it twice: once in the empty-arg check, once in the value check.
	queriesBuf, err := os.ReadFile(filepath.Join(dir, "store", "events", "queries.sql"))
	if err != nil {
		t.Fatalf("read queries.sql: %v", err)
	}
	queriesText := string(queriesBuf)
	// Count occurrences of filter_status - should be 4 (2 in ListEvents, 2 in CountEvents)
	// because it appears in "(sqlc.arg(filter_status) = '' OR status = sqlc.arg(filter_status))"
	filterCount := strings.Count(queriesText, "sqlc.arg(filter_status)")
	if filterCount != 4 {
		t.Errorf("sqlc.arg(filter_status) appears %d times, want 4 (2 in ListEvents, 2 in CountEvents)", filterCount)
	}
}
