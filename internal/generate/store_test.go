func TestEmitStoreReturnsEmittedPaths(t *testing.T) {
	dir := t.TempDir()
	r := fixtureResource()

	paths, err := EmitStore(dir, []rastrillo.Resource{r})
	if err != nil {
		t.Fatalf("EmitStore: %v", err)
	}
	want := []string{
		filepath.Join(dir, "store", "sqlc.yaml"),
		filepath.Join(dir, "store", "notes", "schema.sql"),
		filepath.Join(dir, "store", "notes", "queries.sql"),
		filepath.Join(dir, "store", "notes", "migrations.go"),
	}
	if len(paths) != len(want) {
		t.Fatalf("paths = %v, want %v", paths, want)
	}
	for i := range want {
		if paths[i] != want[i] {
			t.Errorf("paths[%d] = %q, want %q", i, paths[i], want[i])
		}
	}
}

func TestEmitStoreIsIdempotent(t *testing.T) {
	dir := t.TempDir()
	r := fixtureResource()

	paths, err := EmitStore(dir, []rastrillo.Resource{r})
	if err != nil {
		t.Fatalf("EmitStore (1st): %v", err)
	}
	first := readAllFiles(t, paths)

	if _, err := EmitStore(dir, []rastrillo.Resource{r}); err != nil {
		t.Fatalf("EmitStore (2nd): %v", err)
	}
	second := readAllFiles(t, paths)

	for _, p := range paths {
		if first[p] != second[p] {
			t.Errorf("%s changed between runs", p)
		}
	}
}

func readAllFiles(t *testing.T, paths []string) map[string]string {
	t.Helper()
	out := map[string]string{}
	for _, p := range paths {
		b, err := os.ReadFile(p)
		if err != nil {
			t.Fatalf("read %s: %v", p, err)
		}
		out[p] = string(b)
	}
	return out
}

