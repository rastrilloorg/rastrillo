func TestEmitStoreIsIdempotent(t *testing.T) {
	dir := t.TempDir()
	r := fixtureResource()

	paths, _, err := EmitStore(dir, []rastrillo.Resource{r}, nil)
	if err != nil {
		t.Fatalf("EmitStore (1st): %v", err)
	}
	first := readAllFiles(t, paths)

	if _, _, err := EmitStore(dir, []rastrillo.Resource{r}, nil); err != nil {
		t.Fatalf("EmitStore (2nd): %v", err)
	}
	second := readAllFiles(t, paths)

	for _, p := range paths {
		if first[p] != second[p] {
			t.Errorf("%s changed between runs", p)
		}
	}
}

func readAllFiles(t *testing.T, paths []string) map[string]string {
	t.Helper()
	out := map[string]string{}
	for _, p := range paths {
		b, err := os.ReadFile(p)
		if err != nil {
			t.Fatalf("read %s: %v", p, err)
		}
		out[p] = string(b)
	}
	return out
}

