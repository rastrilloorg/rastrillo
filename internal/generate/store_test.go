// fixtureResource is the plan's running example (also validResource in the
// root package's manifest_test.go): a "notes" resource with a Title/Price
// list, Search on, a Title filter, and Title/Body basics plus a Price
// advanced field. EmitStore documents its input as validated with kinds
// already normalized, so this fixture runs through Validate — exactly
// what a real caller (the manifest loader) would hand it.
func fixtureResource() rastrillo.Resource {
	r := rastrillo.Resource{
		Name:  "notes",
		Route: "/admin/notes",
		Store: rastrillo.Exclusive,
		List: rastrillo.List{
			Columns: []rastrillo.Column{{Field: "Title"}, {Field: "Price", Kind: rastrillo.Money}},
			Search:  true,
			Filter:  []string{"Title"},
		},
		Form: rastrillo.Form{
			Basics:   []rastrillo.Field{{Name: "Title"}, {Name: "Body", Kind: rastrillo.Textarea}},
			Advanced: []rastrillo.Field{{Name: "Price", Kind: rastrillo.Money}},
		},
	}
	if err := r.Validate(); err != nil {
		panic(err) // fixture must stay valid; a break here is a test bug
	}
	return r
}

