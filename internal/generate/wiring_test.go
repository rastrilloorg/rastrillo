// checkWiring starts mix on a database file from before money had a
// currency, checks what Boot did to it, starts it again, then breaks
// one row of each kind of store and checks the start is refused.
func checkWiring(t *testing.T, app string, mix wiringMix, ledger bool) {
	db := filepath.Join(t.TempDir(), "app.db")
	todaysDatabase(t, db, mix, ledger)
	env := []string{"DB=" + db, "LEDGER=0"}
	if ledger {
		env[1] = "LEDGER=1"
	}
	step := func(name string, extra ...string) {
		t.Helper()
		if out, err := runSteps(app, "TestStep", append(append([]string{"STEP=" + name}, env...), extra...)...); err != nil {
			t.Fatalf("step %s %v: %v\n%s", name, extra, err, out)
		}
	}

	step("start", "PAGES="+mix.pages)
	if mix.fees {
		assertRow(t, db, `SELECT price_minor, price_currency, (SELECT COUNT(*) FROM pragma_table_info('fees') WHERE name = 'price') FROM fees`, "1250 USD 0")
	}
	if mix.prices {
		assertRow(t, db, `SELECT group_concat(name) FROM pragma_table_info('eventlog') WHERE name LIKE 'payload%'`, "payload_v2")
		assertRow(t, db, `SELECT stream, seq FROM eventlog_upgrade WHERE stream = 'prices/1'`, "prices/1 1")
	} else {
		assertRow(t, db, `SELECT COUNT(*) FROM sqlite_master WHERE name LIKE 'eventlog%'`, "0")
	}
	if ledger && !slices.Contains(ledgerIDs(t, db), "eventlog_money/0001_payload_v2") {
		t.Errorf("ledger %v lacks eventlog_money/0001_payload_v2", ledgerIDs(t, db))
	}

	upgraded := dumpDB(t, db)
	step("start", "PAGES="+mix.pages)
	if again := dumpDB(t, db); again != upgraded {
		t.Errorf("a second start changed the database:\nafter the first:\n%s\nafter the second:\n%s", upgraded, again)
	}

	if mix.fees {
		execDB(t, db, `INSERT INTO fees (title, price_minor, price_currency, created_at, updated_at) VALUES ('Bad', 5, NULL, 'x', 'x')`)
		step("refuse", "WANT=fees.price: 1 rows have an amount without a currency or a currency without an amount; fix them before starting")
		execDB(t, db, `DELETE FROM fees WHERE title = 'Bad'`)
	}
	if mix.notes {
		// A store without money is replayed at boot too: spec §7 refuses
		// an unknown version with or without money fields.
		appendEvent(t, db, "notes/1", "updated", `{"V":3}`)
		step("refuse", "WANT=notes/1: event 1: version 3 is not one this binary understands")
		execDB(t, db, `DELETE FROM eventlog WHERE writer = 'w9'`)
	}
	if mix.prices {
		appendEvent(t, db, "prices/1", "updated", `{"V":3}`)
		step("refuse", "WANT=prices/1: event 1: version 3 is not one this binary understands")
	}
}

// todaysDatabase writes path as the binary from before money had a
// currency left it: its tables applied the way the app applies them
// (eventlog.Schema's DDL run raw, as Options.Migrations does, or
// through the ledger), one legacy row per store.
func todaysDatabase(t *testing.T, path string, mix wiringMix, ledger bool) {
	t.Helper()
	ctx := context.Background()
	db, err := rastrillo.OpenDB(path, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	events := mix.prices || mix.notes
	switch {
	case ledger:
		set := migrate.Merge(eventlog.Schema)
		if mix.fees {
			set = migrate.Merge(eventlog.Schema, new(migrate.Set).Add(migrate.Migration{ID: "fees_gen/0001_init", SQL: todaysFeesStatement}))
		}
		if _, err := migrate.Apply(ctx, migrate.Pool(db), set); err != nil {
			t.Fatal(err)
		}
	default:
		var stmts []string
		if mix.fees {
			stmts = append(stmts, todaysFeesStatement)
		}
		if events {
			for _, m := range eventlog.Schema.All() {
				stmts = append(stmts, m.SQL)
			}
		}
		for _, s := range stmts {
			if _, err := db.Exec(s); err != nil {
				t.Fatal(err)
			}
		}
	}
	if mix.fees {
		if _, err := db.Exec(`INSERT INTO fees (title, price, created_at, updated_at) VALUES ('Lunch', 1250, 'x', 'x')`); err != nil {
			t.Fatal(err)
		}
	}
	if !events {
		return
	}
	writer, err := eventlog.LocalWriter(ctx, db)
	if err != nil {
		t.Fatal(err)
	}
	l, err := eventlog.Open(db, writer)
	if err != nil {
		t.Fatal(err)
	}
	for stream, payload := range map[string]string{"prices/1": todaysPriceEvent, "notes/1": todaysNoteEvent} {
		if strings.HasPrefix(stream, "prices") && !mix.prices || strings.HasPrefix(stream, "notes") && !mix.notes {
			continue
		}
		if _, err := l.Append(ctx, stream, "created", "app", json.RawMessage(payload)); err != nil {
			t.Fatal(err)
		}
	}
}

func execDB(t *testing.T, path, q string) {
	t.Helper()
	db := openDB(t, path)
	if _, err := db.Exec(q); err != nil {
		t.Fatalf("%s: %v", q, err)
	}
	db.Close()
}

// appendEvent appends as another writer, on the upgraded log.
func appendEvent(t *testing.T, path, stream, kind, payload string) {
	t.Helper()
	db := openDB(t, path)
	defer db.Close()
	l, err := eventlog.Open(db, "w9")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := l.Append(context.Background(), stream, kind, "human", json.RawMessage(payload)); err != nil {
		t.Fatal(err)
	}
}

// dumpDB is every table's schema and rows, sorted, so two dumps are
// equal exactly when a start changed nothing.
func dumpDB(t *testing.T, path string) string {
	t.Helper()
	db := openDB(t, path)
	defer db.Close()
	tables, err := db.Query(`SELECT name, sql FROM sqlite_master WHERE type = 'table' ORDER BY name`)
	if err != nil {
		t.Fatal(err)
	}
	var names, out []string
	for tables.Next() {
		var name, ddl string
		if err := tables.Scan(&name, &ddl); err != nil {
			t.Fatal(err)
		}
		names = append(names, name)
		out = append(out, ddl)
	}
	tables.Close()
	for _, name := range names {
		rows, err := db.Query(`SELECT * FROM "` + name + `"`)
		if err != nil {
			t.Fatal(err)
		}
		cols, _ := rows.Columns()
		var lines []string
		for rows.Next() {
			vals := make([]any, len(cols))
			ptrs := make([]any, len(cols))
			for i := range vals {
				ptrs[i] = &vals[i]
			}
			if err := rows.Scan(ptrs...); err != nil {
				t.Fatal(err)
			}
			lines = append(lines, name+": "+fmt.Sprint(vals...))
		}
		rows.Close()
		sort.Strings(lines)
		out = append(out, lines...)
	}
	return strings.Join(out, "\n")
}

