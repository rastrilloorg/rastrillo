// The race tests pause a request at one exact point: after the nth
// read of a stream's history, on a handle opened through hookedDriver,
// they run another writer's events on a separate handle, then let the
// request go on. Waiting on timing instead could pass by luck.
type hookedDriver struct{ driver.Driver }

func (d hookedDriver) Open(name string) (driver.Conn, error) {
	c, err := d.Driver.Open(name)
	return hookedConn{c}, err
}

type hookedConn struct{ driver.Conn }

func (c hookedConn) QueryContext(ctx context.Context, q string, args []driver.NamedValue) (driver.Rows, error) {
	var after func()
	switch {
	// The read of a resource's streams: the names alone, as AppendUnder
	// reads them under the lock, or every event under the prefix, as the
	// store read them before it allocated under the lock, so the step
	// pauses either Create.
	case strings.HasPrefix(strings.TrimSpace(q), "SELECT DISTINCT stream"), strings.Contains(q, "WHERE stream LIKE ?"):
		after = takePrefixStep()
	case strings.HasPrefix(strings.TrimSpace(q), "SELECT stream, writer, seq") && strings.Contains(q, "WHERE stream = ?"):
		n := nextRead()
		after = func() { runStep(n, false) }
	default:
		return c.Conn.(driver.QueryerContext).QueryContext(ctx, q, args)
	}
	rows, err := c.Conn.(driver.QueryerContext).QueryContext(ctx, q, args)
	if err != nil {
		return rows, err
	}
	return hookedRows{rows, after}, nil
}

func (c hookedConn) ExecContext(ctx context.Context, q string, args []driver.NamedValue) (driver.Result, error) {
	return c.Conn.(driver.ExecerContext).ExecContext(ctx, q, args)
}

func (c hookedConn) BeginTx(ctx context.Context, opts driver.TxOptions) (driver.Tx, error) {
	return c.Conn.(driver.ConnBeginTx).BeginTx(ctx, opts)
}

type hookedRows struct {
	driver.Rows
	after func()
}

// Close runs the read's after-step once the read has released its
// statement, so the other writer is not blocked by it.
func (r hookedRows) Close() error {
	err := r.Rows.Close()
	if r.after != nil {
		r.after()
	}
	return err
}

// prefixStep runs once, after the next read of the streams under a
// prefix: the read a Create allocates its id from. It is counted apart
// from the stream reads so arming it never shifts their numbering.
var prefixStep struct {
	sync.Mutex
	fn func()
}

func afterPrefixRead(fn func()) {
	prefixStep.Lock()
	prefixStep.fn = fn
	prefixStep.Unlock()
}

func takePrefixStep() func() {
	prefixStep.Lock()
	defer prefixStep.Unlock()
	fn := prefixStep.fn
	prefixStep.fn = nil
	return fn
}

// A readStep runs fn before or after the nth stream read since onReads
// armed it. A before-step runs while the request holds no lock, which
// is the only safe moment between a refused append and the next read:
// an after-step on the read inside AppendChecked would run under the
// write lock, and its writer would wait out busy_timeout.
type readStep struct {
	n      int
	before bool
	fn     func()
}

var readHook struct {
	sync.Mutex
	count int
	steps []readStep
}

func onReads(steps ...readStep) {
	readHook.Lock()
	readHook.count, readHook.steps = 0, steps
	readHook.Unlock()
}

// afterRead runs fn once, after the nth stream read from now.
func afterRead(n int, fn func()) { onReads(readStep{n, false, fn}) }

// nextRead counts one stream read and runs its before-step.
func nextRead() int {
	readHook.Lock()
	readHook.count++
	n := readHook.count
	readHook.Unlock()
	runStep(n, true)
	return n
}

func runStep(n int, before bool) {
	readHook.Lock()
	var fn func()
	for _, s := range readHook.steps {
		if s.n == n && s.before == before {
			fn = s.fn
		}
	}
	readHook.Unlock()
	if fn != nil {
		fn()
	}
}

var registerHooked sync.Once

// openHooked opens path as rastrillo.OpenDB does, through hookedDriver.
func openHooked(t *testing.T, path string) *sql.DB {
	t.Helper()
	registerHooked.Do(func() {
		plain, _ := sql.Open("sqlite", "")
		sql.Register("sqlite-hooked", hookedDriver{plain.Driver()})
		plain.Close()
	})
	db, err := sql.Open("sqlite-hooked", path+"?_pragma=busy_timeout(5000)&_pragma=journal_mode(WAL)")
	if err != nil {
		t.Fatal(err)
	}
	db.SetMaxOpenConns(1)
	t.Cleanup(func() { db.Close() })
	return db
}

// openPlain is a second, unhooked handle on path: the other writer.
func openPlain(t *testing.T, path string) *sql.DB {
	t.Helper()
	return openWithTimeout(t, path, 5000)
}

// openImpatient is the other writer on a handle that does not wait for
// the write lock: a write that finds it taken fails at once, which is
// how a test sees that the paused request holds it.
func openImpatient(t *testing.T, path string) *sql.DB {
	t.Helper()
	return openWithTimeout(t, path, 0)
}

func openWithTimeout(t *testing.T, path string, busyTimeout int) *sql.DB {
	t.Helper()
	db, err := sql.Open("sqlite", fmt.Sprintf("%s?_pragma=busy_timeout(%d)&_pragma=journal_mode(WAL)", path, busyTimeout))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { db.Close() })
	return db
}

