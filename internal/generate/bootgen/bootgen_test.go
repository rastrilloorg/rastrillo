// The SQL step for examples/tickets' one money store, byte for byte.
func TestEmitBootUpgradesSQLMoney(t *testing.T) {
	gen := filepath.Join(t.TempDir(), "gen")
	scale := 2
	rs := []rastrillo.Resource{{Name: "ticket_types", Route: "/admin/ticket_types"}}
	sql := []Table{{Name: "ticket_types", Fields: []string{"price"}, Legacy: &rastrillo.Legacy{Currency: "USD", Scale: &scale}}}
	if _, _, err := Emit(gen, rs, sql, nil); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(gen, "boot.go"))
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != wantTicketsBoot {
		t.Errorf("gen/boot.go =\n%s\nwant\n%s", got, wantTicketsBoot)
	}
}

// Without [legacy] the table's Legacy is left out (nil), and currency
// is not imported for it.
func TestEmitBootWithoutLegacy(t *testing.T) {
	gen := filepath.Join(t.TempDir(), "gen")
	rs := []rastrillo.Resource{{Name: "fees", Route: "/fees"}}
	if _, _, err := Emit(gen, rs, []Table{{Name: "fees", Fields: []string{"price", "deposit"}}}, nil); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(gen, "boot.go"))
	if err != nil {
		t.Fatal(err)
	}
	want := "\t\t{Name: \"fees\", Fields: []string{\"price\", \"deposit\"}},\n"
	if !strings.Contains(string(got), want) || strings.Contains(string(got), `"amadan.net/rastrillo/rastrillo/currency"`) {
		t.Errorf("gen/boot.go lacks %q or imports currency it does not use:\n%s", want, got)
	}
}

const wantMixedBoot = `// Code generated by rastrillo generate; DO NOT EDIT.

package gen

import (
	"context"
	"database/sql"

	"amadan.net/rastrillo/rastrillo/currency/sqlmoney"
	"amadan.net/rastrillo/rastrillo/eventlog"
	invoicesstore "scratch/gen/store/invoices"
	pricesstore "scratch/gen/store/prices"
)

// Booted proves Boot ran for this database. Router takes it so an app
// cannot serve without it.
type Booted struct{ db *sql.DB }

// Boot upgrades this app's money data once and checks it, then returns
// the value Router needs. Call it after the schema is applied and
// before serving; a non-nil error must stop the start.
func Boot(ctx context.Context, db *sql.DB) (Booted, error) {
	if err := eventlog.UpgradeForMoney(ctx, db); err != nil {
		return Booted{}, err
	}
	if err := sqlmoney.Upgrade(ctx, db, []sqlmoney.Table{
		{Name: "fees", Fields: []string{"price"}},
	}); err != nil {
		return Booted{}, err
	}
	if err := invoicesstore.CheckReplay(ctx, db); err != nil {
		return Booted{}, err
	}
	if err := pricesstore.CheckReplay(ctx, db); err != nil {
		return Booted{}, err
	}
	return Booted{db: db}, nil
}
`

// The event log is renamed before anything reads it, the SQL tables
// are upgraded next, and only then is every mergeable store replayed,
// the one without money too: replay reads payload_v2 and the boundary
// the rename snapshots.
func TestEmitBootUpgradesEventMoney(t *testing.T) {
	gen := filepath.Join(t.TempDir(), "gen")
	rs := []rastrillo.Resource{{Name: "fees"}, {Name: "invoices"}, {Name: "prices"}}
	events := []EventStore{
		{Name: "invoices", Alias: "invoicesstore", Path: "scratch/gen/store/invoices"},
		{Name: "prices", Alias: "pricesstore", Path: "scratch/gen/store/prices", Money: true},
	}
	if _, _, err := Emit(gen, rs, []Table{{Name: "fees", Fields: []string{"price"}}}, events); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(gen, "boot.go"))
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != wantMixedBoot {
		t.Errorf("gen/boot.go =\n%s\nwant\n%s", got, wantMixedBoot)
	}
}

// generate says the event log will be renamed exactly when a run adds
// the rename to Boot: a later run that keeps it says nothing, because
// the deploy that renames is the one after the first.
func TestEmitNoticesTheEventLogRenameOnce(t *testing.T) {
	gen := filepath.Join(t.TempDir(), "gen")
	rs := []rastrillo.Resource{{Name: "notes"}, {Name: "prices"}}
	notes := EventStore{Name: "notes", Alias: "notesstore", Path: "scratch/gen/store/notes"}
	prices := []EventStore{notes, {Name: "prices", Alias: "pricesstore", Path: "scratch/gen/store/prices", Money: true}}
	want := []string{"prices keeps money in events, so the next deploy renames the event log's payload column. Take a backup, stop every running copy, then start the new version. Never run old and new versions side by side. To go back, restore the backup."}
	for _, run := range []struct {
		name   string
		events []EventStore
		want   []string
	}{
		{"no money in events yet", []EventStore{notes}, nil},
		{"money added", prices, want},
		{"unchanged", prices, nil},
	} {
		_, notices, err := Emit(gen, rs, nil, run.events)
		if err != nil {
			t.Fatal(err)
		}
		if !reflect.DeepEqual(notices, run.want) {
			t.Errorf("%s: notices %q, want %q", run.name, notices, run.want)
		}
	}
}

// A store without money is replayed at boot, so an event from a newer
// writer stops the start, but its app's event log is not renamed.
func TestEmitBootReplaysAStoreWithoutMoney(t *testing.T) {
	gen := filepath.Join(t.TempDir(), "gen")
	notes := []EventStore{{Name: "notes", Alias: "notesstore", Path: "scratch/gen/store/notes"}}
	if _, _, err := Emit(gen, []rastrillo.Resource{{Name: "notes"}}, nil, notes); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(gen, "boot.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), "if err := notesstore.CheckReplay(ctx, db); err != nil {") || strings.Contains(string(got), "eventlog") {
		t.Errorf("gen/boot.go for a store without money:\n%s", got)
	}
}

// An unreadable boot.go is an error, not "no boot.go", which would
// announce a rename the app already had.
func TestEmitRefusesAnUnreadableBoot(t *testing.T) {
	gen := t.TempDir()
	if err := os.Mkdir(filepath.Join(gen, "boot.go"), 0o755); err != nil {
		t.Fatal(err)
	}
	prices := []EventStore{{Name: "prices", Alias: "pricesstore", Path: "scratch/gen/store/prices", Money: true}}
	if _, notices, err := Emit(gen, []rastrillo.Resource{{Name: "prices"}}, nil, prices); err == nil || notices != nil {
		t.Errorf("Emit over a boot.go it cannot read = %q, %v", notices, err)
	}
}
