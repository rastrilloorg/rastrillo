// TestListHTMLDropdownMatchesPartial is the brief's markup-equivalence
// test: it renders the inline <details rst-dropdown> block
// listHTML emits for a Filters-declared resource and separately renders
// the real "dropdown" partial (ui/partials/dropdown.html) given the
// SAME already-resolved Label/Aria strings the inline block's (T
// .LabelKey) / (T .Filter.AriaField) / (T .Filter.SummaryKey) calls
// would produce, then asserts the two render byte-identical HTML — the
// binding decision's whole premise (same attributes, same a11y contract)
// only holds if this stays true.
func TestListHTMLDropdownMatchesPartial(t *testing.T) {
	appRoot := t.TempDir()
	genDir := t.TempDir()
	r := filteredFixtureResource()

	if _, _, err := EmitTemplates(appRoot, genDir, r); err != nil {
		t.Fatalf("EmitTemplates: %v", err)
	}

	// tKeys is the resolved-string counterpart to what the generated
	// action's filterView actually carries as KEYS (see actions.go):
	// ui.all, resource.events.field.status, and one
	// resource.events.filter.status.<value> per declared value.
	tKeys := map[string]string{
		"ui.all":                              "All",
		"resource.events.field.status":        "Status",
		"resource.events.filter.status.draft": "Drafts",
		"resource.events.filter.status.live":  "Live",
	}
	T := func(k string) string {
		if v, ok := tKeys[k]; ok {
			return v
		}
		return k
	}

	// Bound through ui.WithT, not registered as "T": ui's partials now
	// call T $L "key", which a one-argument T cannot take.
	tmpl := template.New("").Funcs(ui.Funcs(ui.WithT(func(k string, _ ...any) string { return T(k) })))
	tmpl, err := tmpl.ParseFS(ui.Templates(), "*.html")
	if err != nil {
		t.Fatalf("parse ui templates: %v", err)
	}
	// list.html alone, not a glob of the whole events/ directory: show.html
	// and form.html each define their OWN "content" template too (the
	// three screens share that one name deliberately — see
	// buildPages' own doc in examples/blog/internal/blog/render.go), and
	// parsing more than one into a single tree would let whichever file
	// sorts last silently clobber list.html's "content" definition.
	tmpl, err = tmpl.ParseFiles(filepath.Join(genDir, "templates", "events", "list.html"))
	if err != nil {
		t.Fatalf("parse emitted list.html: %v", err)
	}

	type filterItem struct {
		Href     string
		LabelKey string
		Current  bool
	}
	type filterView struct {
		SummaryKey string
		AriaField  string
		Items      []filterItem
	}
	data := struct {
		Empty      bool
		Query      string
		Carry      [][2]string
		Filter     filterView
		Rows       []struct{ Href, Main, Sub string }
		Pagination struct {
			Show  bool
			Items []struct{}
		}
	}{
		Filter: filterView{
			// The applied value: draft. Exercises Current on a real
			// (non-All) item as well as the All item's Current == false.
			SummaryKey: "resource.events.filter.status.draft",
			AriaField:  "resource.events.field.status",
			Items: []filterItem{
				{Href: "/admin/events", LabelKey: "ui.all", Current: false},
				{Href: "/admin/events?status=draft", LabelKey: "resource.events.filter.status.draft", Current: true},
				{Href: "/admin/events?status=live", LabelKey: "resource.events.filter.status.live", Current: false},
			},
		},
	}

	var buf bytes.Buffer
	if err := tmpl.ExecuteTemplate(&buf, "content", data); err != nil {
		t.Fatalf("execute content: %v", err)
	}

	// The open tag now carries the shared exclusivity group
	// (name="rst-menus"), so match up to the closing angle bracket rather
	// than pinning the exact attribute list here — the byte comparison
	// against the real partial below is what holds the two identical,
	// name attribute included.
	re := regexp.MustCompile(`(?s)<details rst-dropdown[^>]*>.*?</details>`)
	got := re.FindString(buf.String())
	if got == "" {
		t.Fatalf("no <details %s> block found in rendered content:\n%s", "rst-dropdown", buf.String())
	}

	partialData := map[string]any{
		"Label": "Drafts",
		"Aria":  "Filter by Status: Drafts",
		"Items": []map[string]any{
			{"Href": "/admin/events", "Label": "All", "Current": false},
			{"Href": "/admin/events?status=draft", "Label": "Drafts", "Current": true},
			{"Href": "/admin/events?status=live", "Label": "Live", "Current": false},
		},
	}
	var want bytes.Buffer
	if err := tmpl.ExecuteTemplate(&want, "dropdown", partialData); err != nil {
		t.Fatalf("execute dropdown partial: %v", err)
	}

	if got != want.String() {
		t.Errorf("inline dropdown block does not match the real partial's render:\ngot:\n%s\nwant:\n%s", got, want.String())
	}
}

