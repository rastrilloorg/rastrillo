package prune

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

func tree(t *testing.T, files map[string]string) string {
	t.Helper()
	gen := filepath.Join(t.TempDir(), "gen")
	for rel, content := range files {
		p := filepath.Join(gen, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return gen
}

// Each format's header is recognised in its own comment syntax, and
// only there: the same words opening a Markdown file are the app's.
func TestStaleReadsEachFormatsHeader(t *testing.T) {
	gen := tree(t, map[string]string{
		"store/x/store.go":          "// Code generated by rastrillo generate; DO NOT EDIT.\npackage x\n",
		"router.go":                 "// Code generated by rastrillo generate. DO NOT EDIT.\npackage gen\n",
		"store/x/schema.sql":        "-- Code generated by rastrillo generate; DO NOT EDIT.\n",
		"store/sqlc.yaml":           "# Code generated by rastrillo generate; DO NOT EDIT.\n",
		"locales/en.toml":           "# Code generated by rastrillo generate; DO NOT EDIT.\n",
		"templates/x/list.html":     "{{/* Code generated by rastrillo generate; DO NOT EDIT.\n*/}}\n",
		"manifest.json":             "[]\n",
		"store/x/README.md":         "# Code generated by rastrillo generate\n",
		"store/x/mine.go":           "package x\n",
		"templates/x/mine.html":     "<p>mine</p>\n",
		"store/x/other.json":        "{}\n",
		"store/x/written.go":        "// Code generated by rastrillo generate; DO NOT EDIT.\npackage x\n",
		"templates/x/mislabel.html": "// Code generated by rastrillo generate\n",
	})
	got, err := Stale(gen, []string{filepath.Join(gen, "store", "x", "written.go")}, nil)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"gen/locales/en.toml",
		"gen/manifest.json",
		"gen/router.go",
		"gen/store/sqlc.yaml",
		"gen/store/x/schema.sql",
		"gen/store/x/store.go",
		"gen/templates/x/list.html",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("Stale = %q, want %q", got, want)
	}
}

// sqlc's output belongs to the run only in a store that is exclusive
// now; the same files in a store that turned mergeable would declare
// Queries and New a second time.
func TestSqlcOutputFollowsTheExclusiveStores(t *testing.T) {
	sqlc := "// Code generated by sqlc. DO NOT EDIT.\npackage x\n"
	gen := tree(t, map[string]string{"store/a/db.go": sqlc, "store/b/db.go": sqlc, "store/b/models.go": sqlc})
	got, err := Stale(gen, nil, []string{filepath.Join(gen, "store", "a")})
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"gen/store/b/db.go", "gen/store/b/models.go"}; !reflect.DeepEqual(got, want) {
		t.Errorf("Stale = %q, want %q", got, want)
	}
}

func TestPruneRemovesFilesAndTheDirectoriesTheyLeaveEmpty(t *testing.T) {
	header := "// Code generated by rastrillo generate; DO NOT EDIT.\npackage x\n"
	gen := tree(t, map[string]string{
		"actions/b/index_get/index.GET.go": header,
		"store/b/store.go":                 header,
		"store/b/notes.md":                 "mine",
		"router.go":                        header,
	})
	removed, err := Prune(gen, []string{filepath.Join(gen, "router.go")}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"gen/actions/b/index_get/index.GET.go", "gen/store/b/store.go"}; !reflect.DeepEqual(removed, want) {
		t.Errorf("removed %q, want %q", removed, want)
	}
	if _, err := os.Stat(filepath.Join(gen, "actions")); !os.IsNotExist(err) {
		t.Errorf("gen/actions was left behind empty: %v", err)
	}
	for _, kept := range []string{"store/b/notes.md", "router.go"} {
		if _, err := os.Stat(filepath.Join(gen, kept)); err != nil {
			t.Errorf("gen/%s was removed: %v", kept, err)
		}
	}
	if again, err := Prune(gen, []string{filepath.Join(gen, "router.go")}, nil); err != nil || len(again) != 0 {
		t.Errorf("a second Prune removed %q, %v", again, err)
	}
}

func TestNoGeneratedTreeIsNothingStale(t *testing.T) {
	got, err := Stale(filepath.Join(t.TempDir(), "gen"), nil, nil)
	if err != nil || len(got) != 0 {
		t.Errorf("Stale on a missing gen/ = %q, %v", got, err)
	}
}
