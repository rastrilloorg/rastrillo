// Package apigen emits the API doors: gen/api/<resource>/doors.go
// for every exposed resource, and gen/api.go, the one file an app's
// main.go imports to mount them all. A door is thin on purpose: it
// decodes the request, calls the operation gen/ops already holds, and
// writes the answer, so a rule written in the operation reaches the
// API without a second copy here. The goldens under testdata/api are
// the contract for what is emitted.
package apigen

import (
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strings"

	"amadan.net/rastrillo/rastrillo"
	"amadan.net/rastrillo/rastrillo/internal/generate/shape"
	"amadan.net/rastrillo/rastrillo/internal/wirename"
)

// commentWidth is the text width the goldens pin, after the "// ".
const commentWidth = 69

// header starts every file so prune can tell it from a hand-written one.
const header = "// Code generated by rastrillo generate. DO NOT EDIT.\n\n"

// msgLimit is the 422 for a limit that is not an integer. The range is
// named so a client that sent 0 or 500 learns what the operation will
// clamp it to without a second request.
const msgLimit = "Use a whole number from 1 to 200."

// Emit writes gen/api/<name>/doors.go for r, package api_<name>, and
// returns the one path it wrote, or nothing for a resource that is not
// exposed: no file, no directory, and no path claimed, so prune
// removes the doors of a resource taken off the API. The file name is
// fixed rather than the resource's: <name>.go for orders_test or
// orders_windows would be a test file or a Windows-only one, and the
// package would lose Routes in every other build.
func Emit(appRoot, genDir string, r rastrillo.Resource) (written []string, err error) {
	if !r.Exposed() {
		return nil, nil
	}
	module, err := shape.ModulePath(appRoot)
	if err != nil {
		return nil, err
	}
	src := header + doorsGo(r, module)
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("api/%s/doors.go: %w\n%s", r.Name, err, src)
	}
	path := filepath.Join(genDir, "api", r.Name, "doors.go")
	if err := shape.WriteFile(path, formatted); err != nil {
		return nil, fmt.Errorf("api/%s/doors.go: %w", r.Name, err)
	}
	return []string{path}, nil
}

// Door is one of a resource's five API routes: the action that names
// its operation ("list" in "bookmarks.list"), the method and pattern
// the doors file registers, and the access its operation declares.
type Door struct {
	Action  string
	Method  string // http.MethodGet's value, "GET"
	Pattern string // "/api/v1/bookmarks/{id}"
	Access  rastrillo.Access
	opVar   string // ops_<name>.<opVar>, "ListOp"
	handler string // the handler in the doors file, "remove" for delete
}

// Doors is r's routes in the order Routes lists them. Routes in the
// doors file and the committed api/v1.json (internal/generate/contract)
// both read this one list, so the contract cannot name a route the
// doors do not serve, or miss one they do. Access is repeated from
// opsgen's operations here because the contract records it and the
// doors file does not; contract's tests pin the two against opsgen's
// goldens.
func Doors(r rastrillo.Resource) []Door {
	base := "/api/v1/" + r.Name
	return []Door{
		{"list", "GET", base, rastrillo.Read, "ListOp", "list"},
		{"create", "POST", base, rastrillo.Write, "CreateOp", "create"},
		{"get", "GET", base + "/{id}", rastrillo.Read, "GetOp", "get"},
		{"update", "PATCH", base + "/{id}", rastrillo.Write, "UpdateOp", "update"},
		{"delete", "DELETE", base + "/{id}", rastrillo.Write, "DeleteOp", "remove"},
	}
}

// methodConst is the net/http constant for a Door.Method, so the doors
// file reads as the goldens pin it rather than as a string literal.
func methodConst(method string) string {
	return "http.Method" + strings.ToUpper(method[:1]) + strings.ToLower(method[1:])
}

// local is the name a door gives the row an operation answers: the
// singular's first letter, as "b" for a bookmark. r and w are the
// handler's own parameters, so a resource whose singular starts with
// either (remotes, widgets) would shadow the request or the writer
// and the file would not compile; those take "row".
func local(r rastrillo.Resource) string {
	l := strings.ToLower(shape.SingularPascal(r.Name)[:1])
	if l == "r" || l == "w" {
		return "row"
	}
	return l
}

// doorsGo renders the doors file: Routes, one handler per door, and
// pathID. Only the package doc, the names and the list's input lines
// differ between resources.
func doorsGo(r rastrillo.Resource, module string) string {
	pkg, ops, v := "api_"+r.Name, "ops_"+r.Name, local(r)
	var b strings.Builder
	b.WriteString(shape.WrapComment(fmt.Sprintf("Package %s is the %s resource's API doors. Each one decodes the request, calls the operation the page door also calls, and writes the answer; who may do what is op.Check's to decide, not this file's.", pkg, r.Name), commentWidth))
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, `import (
	"context"
	"fmt"
	"net/http"
	"strconv"

	"amadan.net/rastrillo/rastrillo"
	"amadan.net/rastrillo/rastrillo/api"
	"amadan.net/rastrillo/rastrillo/op"
	%s %q
)

`, ops, module+"/gen/ops/"+r.Name)

	fmt.Fprintf(&b, "// Routes is the %s API, for api.New.\n", r.Name)
	fmt.Fprintf(&b, `func Routes() []api.Route {
	d := map[string]op.Descriptor{}
	for _, x := range %[1]s.Descriptors() {
		d[x.ID] = x
	}
	return []api.Route{
`, ops)
	for _, d := range Doors(r) {
		fmt.Fprintf(&b, "\t\t{Method: %s, Pattern: %q, Op: d[%s.%s.ID], Handle: %s},\n", methodConst(d.Method), d.Pattern, ops, d.opVar, d.handler)
	}
	b.WriteString("\t}\n}\n\n")

	// The list's query parameters: q only when the store binds a search,
	// then one per declared filter under its wire name, then the cursor.
	// limit is parsed apart because a non-integer is the client's error
	// to hear about; the operation clamps the rest of the range itself.
	var inputs []string
	if shape.SearchBind(r) {
		inputs = append(inputs, `Search: q.Get("q"),`)
	}
	for _, f := range shape.FilterVars(r) {
		inputs = append(inputs, fmt.Sprintf("%s: q.Get(%q),", f.Param, wirename.Name(f.Field)))
	}
	inputs = append(inputs, `After: q.Get("after"),`)
	fmt.Fprintf(&b, `func list(ctx context.Context, rc *rastrillo.Ctx, w http.ResponseWriter, r *http.Request) {
	q := r.URL.Query()
	in := %[1]s.ListInput{
		%[2]s
	}
	if v := q.Get("limit"); v != "" {
		n, err := strconv.Atoi(v)
		if err != nil {
			api.Refuse(w, r, op.Invalid{Fields: map[string]string{"limit": %[3]q}})
			return
		}
		in.Limit = n
	}
	page, err := %[1]s.List(ctx, rc, in)
	if err != nil {
		api.Refuse(w, r, err)
		return
	}
	api.Write(w, http.StatusOK, page.Result())
}

`, ops, strings.Join(inputs, "\n\t\t"), msgLimit)

	// The body is decoded before {id} is read, in update as in create,
	// so a broken body is 422 whether or not the row exists: spec
	// section 6 puts the body's refusals before the operation's 404.
	// create's Location is a header, so it stays an app path: under a
	// base path the middleware prefixes it once, and basepath.Path here
	// would send the client to /acme/acme/api/v1/….
	fmt.Fprintf(&b, `func create(ctx context.Context, rc *rastrillo.Ctx, w http.ResponseWriter, r *http.Request) {
	var in %[1]s.CreateInput
	if !api.Decode(w, r, &in) {
		return
	}
	%[2]s, err := %[1]s.Create(ctx, rc, in)
	if err != nil {
		api.Refuse(w, r, err)
		return
	}
	w.Header().Set("Location", fmt.Sprintf("/api/v1/%[3]s/%%d", %[2]s.ID))
	api.Write(w, http.StatusCreated, %[2]s)
}

func get(ctx context.Context, rc *rastrillo.Ctx, w http.ResponseWriter, r *http.Request) {
	id, ok := pathID(w, r)
	if !ok {
		return
	}
	%[2]s, err := %[1]s.Get(ctx, rc, id)
	if err != nil {
		api.Refuse(w, r, err)
		return
	}
	api.Write(w, http.StatusOK, %[2]s)
}

func update(ctx context.Context, rc *rastrillo.Ctx, w http.ResponseWriter, r *http.Request) {
	var in %[1]s.UpdateInput
	if !api.Decode(w, r, &in) {
		return
	}
	id, ok := pathID(w, r)
	if !ok {
		return
	}
	%[2]s, err := %[1]s.Update(ctx, rc, id, in)
	if err != nil {
		api.Refuse(w, r, err)
		return
	}
	api.Write(w, http.StatusOK, %[2]s)
}

func remove(ctx context.Context, rc *rastrillo.Ctx, w http.ResponseWriter, r *http.Request) {
	if !api.NoBody(w, r) {
		return
	}
	id, ok := pathID(w, r)
	if !ok {
		return
	}
	if err := %[1]s.Delete(ctx, rc, id); err != nil {
		api.Refuse(w, r, err)
		return
	}
	w.WriteHeader(http.StatusNoContent)
}

// pathID is the {id} path value. One that is not a positive integer
// names no row, so it is the same 404 a missing row gets, as
// view.ParseID answers it on the page.
func pathID(w http.ResponseWriter, r *http.Request) (int64, bool) {
	id, err := strconv.ParseInt(r.PathValue("id"), 10, 64)
	if err != nil || id < 1 {
		api.Refuse(w, r, op.NotFound{})
		return 0, false
	}
	return id, true
}
`, ops, v, r.Name)
	return b.String()
}

// File renders gen/api.go for module: APIRoutes over the exposed
// resources' doors and Operations over every resource's descriptors,
// each sorted by name so a regeneration writes the same bytes. Both
// functions exist whatever rs holds, nil included, so an app's main.go
// keeps compiling as resources come and go from the API.
func File(module string, rs []rastrillo.Resource) ([]byte, error) {
	sorted := append([]rastrillo.Resource(nil), rs...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	var exposed []rastrillo.Resource
	for _, r := range sorted {
		if r.Exposed() {
			exposed = append(exposed, r)
		}
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package gen\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"amadan.net/rastrillo/rastrillo/api\"\n")
	b.WriteString("\t\"amadan.net/rastrillo/rastrillo/op\"\n")
	for _, r := range exposed {
		fmt.Fprintf(&b, "\tapi_%s %q\n", r.Name, module+"/gen/api/"+r.Name)
	}
	for _, r := range sorted {
		fmt.Fprintf(&b, "\tops_%s %q\n", r.Name, module+"/gen/ops/"+r.Name)
	}
	b.WriteString(")\n\n")

	if len(exposed) == 0 {
		b.WriteString("// APIRoutes is every exposed resource's API doors, for api.New. This app\n// exposes none.\nfunc APIRoutes() []api.Route { return nil }\n\n")
	} else {
		b.WriteString("// APIRoutes is every exposed resource's API doors, for api.New.\nfunc APIRoutes() []api.Route {\n\tvar routes []api.Route\n")
		for _, r := range exposed {
			fmt.Fprintf(&b, "\troutes = append(routes, api_%s.Routes()...)\n", r.Name)
		}
		b.WriteString("\treturn routes\n}\n\n")
	}

	if len(sorted) == 0 {
		b.WriteString("// Operations is every resource's operations. This app has none.\nfunc Operations() []op.Descriptor { return nil }\n")
	} else {
		b.WriteString("// Operations is every resource's operations, exposed or not. Each\n// descriptor's Exposed says which, so an MCP server can offer only\n// those without guessing.\nfunc Operations() []op.Descriptor {\n\tvar ops []op.Descriptor\n")
		for _, r := range sorted {
			fmt.Fprintf(&b, "\tops = append(ops, ops_%s.Descriptors()...)\n", r.Name)
		}
		b.WriteString("\treturn ops\n}\n")
	}
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("api.go: %w\n%s", err, b.String())
	}
	return formatted, nil
}
