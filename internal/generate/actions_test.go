// handle is Handle's body. When the operation refuses the save because
// the record's currency changed, it runs again: once more to save, and
// then only to show the form with that message.
func handle(ctx *rastrillo.Ctx, w http.ResponseWriter, r *http.Request, try int) {
	r.Body = http.MaxBytesReader(w, r.Body, 1<<20)
	if err := r.ParseForm(); err != nil {
		http.Error(w, "Bad request.", http.StatusBadRequest)
		return
	}
	id, ok := view.ParseID(r)
	if !ok {
		view.NotFound(ctx, w, r)
		return
	}
	n, err := ops_notes.Get(r.Context(), ctx, id)
	if err != nil {
		view.Refuse(ctx, w, r, "notes: loading notes", err)
		return
	}

	priceCode := currencyOf(n.Price)
	p := form.Parse(r,
		form.Field{Name: "Price", Kind: form.Money, Currency: priceCode, LocaleEcho: true, Stored: minorOf(n.Price)},
	)
	in := ops_notes.UpdateInput{
		Price: clearable(p, "Price", priceCode),
	}
	reshow := func(errs map[string]string) {
		fields := map[string]string{
			"Title": n.Title,
			"Body":  n.Body,
		}
		for k, v := range p.Echo() {
			fields[k] = v
		}
		priceInput, reseed := p.MoneyInput("Price", rastrillo.FormatLocale(r))
		if reseed {
			if priceInput, ok = seed(ctx, w, r, id, "Price", minorOf(n.Price), priceCode); !ok {
				return
			}
		}
		if try == 2 {
			priceInput = form.MoneyInput{Value: p.Echo()["Price"], Locale: r.PostFormValue("Price.locale"), Currency: priceCode}
		}
		view.Render(ctx, w, "notes/form", http.StatusBadRequest, formView{
			Localized: ui.ForRequest(r),
			IsNew:     false,
			Fields:    fields,
			Errors:    errs,
			ErrorArgs: p.ErrorArgs(),
			Money: map[string]form.MoneyInput{
				"Price": priceInput,
			},
			BasicsAction:   fmt.Sprintf("/admin/notes/%d/edit-basics", id),
			AdvancedAction: fmt.Sprintf("/admin/notes/%d/edit-advanced", id),
		})
	}
	if !p.OK() || try == 2 {
		errs := ops_notes.ValidateUpdate(in)
		for k, v := range p.Errors() {
			errs[k] = v
		}
		if try == 2 {
			errs = map[string]string{"Price": "rastrillo.ui.money_currency_changed"}
		}
		reshow(errs)
		return
	}

	_, err = ops_notes.Update(r.Context(), ctx, id, in)
	var invalid op.Invalid
	switch {
	case errors.As(err, &invalid):
		reshow(invalid.Fields)
		return
	case errors.As(err, new(op.Conflict)):
		handle(ctx, w, r, try+1)
		return
	case err != nil:
		view.Refuse(ctx, w, r, "notes: updating notes", err)
		return
	}
	http.Redirect(w, r, fmt.Sprintf("/admin/notes/%d", id), http.StatusSeeOther)
}

