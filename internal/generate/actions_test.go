// TestActionIndexGETListCallShape locks in what index.GET's ListInput
// carries across the four Search/Filter shapes: Search only when the
// store honours it (opsgen's SearchBind, the same gate that puts the
// member on ListInput), so a search-declared resource with no text
// column, which has no Search member, still compiles; one member per
// filter; and page-number mode always. The store's bind-count
// convention is the operation's concern now (opsgen), not the
// action's.
func TestActionIndexGETListCallShape(t *testing.T) {
	cases := []struct {
		name    string
		r       rastrillo.Resource
		want    string // substring the List call must contain
		notWant string // substring that must NOT appear
	}{
		{"neither Search nor Filter", noAdvancedFixtureResource(),
			"res, err := ops_widgets.List(r.Context(), ctx, ops_widgets.ListInput{\nPageNumber: page,\nLimit: pageSize,\n})\n", "Search:"},
		{"Search alone", searchOnlyFixtureResource(),
			"ops_articles.ListInput{\nSearch: search,\nPageNumber: page,\n", "Filter"},
		{"a single Filter alone", filterOnlyFixtureResource(),
			"ops_tags.ListInput{\nFilterTitle: filterTitle,\nPageNumber: page,\n", "Search:"},
		{"Search and a Filter", fixtureResource(),
			"ops_notes.ListInput{\nSearch: search,\nFilterTitle: filterTitle,\nPageNumber: page,\n", ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := actionIndexGET(tc.r, "scratch")
			if !strings.Contains(got, tc.want) {
				t.Errorf("actionIndexGET(%s) missing %q\ngot:\n%s", tc.r.Name, tc.want, got)
			}
			if tc.notWant != "" && strings.Contains(got, tc.notWant) {
				t.Errorf("actionIndexGET(%s) unexpectedly contains %q", tc.r.Name, tc.notWant)
			}
		})
	}
}

