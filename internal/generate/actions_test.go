// newActionsAppRoot builds an app root with just enough of a go.mod for
// actionsModulePath to resolve a module path — EmitActions needs one to
// build the store package's import path, unlike EmitStore/EmitTemplates
// which never emit Go import statements.
func newActionsAppRoot(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module scratch\n\ngo 1.25.0\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

