// localizedSet matches the field as go/format aligns it in a literal.
var localizedSet = regexp.MustCompile(`\n\s*Localized:\s+ui\.ForRequest\(r\),\n`)

// renderedView captures the type of each value handed to view.Render:
// the template's root data, where {{$L := localizer $}} looks for L.
var renderedView = regexp.MustCompile(`view\.Render\(ctx, w, "[^"]+", http\.\w+, (\w+)\{`)

// RenderFunc carries no request, so the app's render function cannot
// find the request's localizer for a generated view: each action must
// put it in the view itself. A render site that forgets renders the
// page in the default language whatever the reader asked for.
func TestEmittedActionsSetLocalized(t *testing.T) {
	appRoot := newActionsAppRoot(t)
	views := 0
	for _, r := range fixtureResources(t) {
		written, _, err := EmitActions(appRoot, t.TempDir(), r)
		if err != nil {
			t.Fatalf("EmitActions(%s): %v", r.Name, err)
		}
		for _, p := range written {
			src, err := os.ReadFile(p)
			if err != nil {
				t.Fatal(err)
			}
			s := string(src)
			renders := strings.Count(s, "view.Render(")
			if renders == 0 {
				continue
			}
			if n := len(localizedSet.FindAllString(s, -1)); n != renders {
				t.Errorf("%s: %d view.Render calls but %d set Localized: ui.ForRequest(r)", p, renders, n)
			}
			if !strings.Contains(s, `"amadan.net/rastrillo/rastrillo/ui"`) {
				t.Errorf("%s renders a view but does not import ui", p)
			}
			for _, m := range renderedView.FindAllStringSubmatch(s, -1) {
				views++
				if !strings.Contains(s, "type "+m[1]+" struct {\n\tui.Localized\n") {
					t.Errorf("%s: %s does not embed ui.Localized first", p, m[1])
				}
			}
		}
	}
	if views == 0 {
		t.Fatal("no view.Render call matched: the pattern no longer fits the emitted code")
	}
}

