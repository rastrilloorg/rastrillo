// Package packs writes gen/locales/packs.go and its test: the blank
// imports of the formatting packs an app's offered locales need, and
// the DefaultLocale and Locales its main wires into rastrillo.Options.
//
// It links no pack itself. locales.PacksFor reads only the core's
// index, which every binary has, so the generator never needs the data
// it decides an app must link.
package packs

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"amadan.net/rastrillo/rastrillo/internal/manifest"
	"amadan.net/rastrillo/rastrillo/locales"
)

// The files Emit owns in gen/locales. The manifest emitters write the
// same directory (locales.go, en.toml), so their idempotency check asks
// Owns before calling one of these an extra file.
const (
	goFile   = "packs.go"
	testFile = "packs_test.go"
)

// Owns reports whether name, a file in gen/locales, is one Emit writes.
func Owns(name string) bool { return name == goFile || name == testFile }

// The comments are Appendix C.6's gen.packs.* (app authors read them),
// wrapped at 72 columns.
const goTemplate = `// Code generated by rastrillo generate; DO NOT EDIT.

// Package locales links the formatting packs manifest/app.toml's
// locales need. Wire DefaultLocale and Locales into rastrillo.Options.
package locales

import (
%s)

// DefaultLocale is manifest/app.toml's default_locale.
const DefaultLocale = %q

// Locales is manifest/app.toml's locales. It is nil when the app
// offers one locale, so a one-locale app gets no /xx/ prefixes and no
// switcher.
%s

var offered = %s
`

// The test carries budget.Main because a scaffolded app's make test is
// rastrillo budget test, which fails any package that ran tests without
// printing its time; without it every new app's gate is red.
const testTemplate = `// Code generated by rastrillo generate; DO NOT EDIT.

package locales

import (
	"os"
	"slices"
	"testing"

	"amadan.net/rastrillo/rastrillo/budget"
	"amadan.net/rastrillo/rastrillo/locales"
)

func TestMain(m *testing.M) { os.Exit(budget.Main(m)) }

// The packs this package imports are exactly the ones its offered
// locales need. generate --check proves this file matches
// manifest/app.toml; the RASTRILLO_CHECK_CONFIG probe proves main links
// this package.
func TestPacksMatchOfferedLocales(t *testing.T) {
	want, err := locales.PacksFor(append([]string{DefaultLocale}, offered...))
	if err != nil {
		t.Fatal(err)
	}
	if got := locales.LinkedPacks(); !slices.Equal(got, want) {
		t.Errorf("gen/locales links %v, manifest/app.toml needs %v: run rastrillo generate", got, want)
	}
}
`

// Appendix C.2's op.config.duplicate, op.config.default_not_offered and
// op.doctor.packs_stale. The identity errors come from
// locales.CanonicalIdentity and PacksFor in their own C.2 words.
const (
	duplicateMsg      = "%q is offered twice"
	defaultNotOffered = "default locale %q is not one of the offered locales %v"
	staleMsg          = "manifest/app.toml offers %v but gen/locales/packs.go was generated for %v; run rastrillo generate"
)

const packPath = "amadan.net/rastrillo/rastrillo/locales/"

// render validates app and returns the two files' bytes. Configuration
// is never repaired: a non-canonical code is refused rather than
// rewritten, because the spelling in app.toml is what routing, cookies
// and catalog file names will use.
func render(app manifest.App) (goSrc, testSrc []byte, err error) {
	seen := map[string]bool{}
	for _, code := range app.Locales {
		if _, err := locales.CanonicalIdentity(code); err != nil {
			return nil, nil, err
		}
		if seen[code] {
			return nil, nil, fmt.Errorf(duplicateMsg, code)
		}
		seen[code] = true
	}
	if !seen[app.DefaultLocale] {
		return nil, nil, fmt.Errorf(defaultNotOffered, app.DefaultLocale, app.Locales)
	}
	packs, err := locales.PacksFor(app.Locales)
	if err != nil {
		return nil, nil, err
	}

	var imports strings.Builder
	for _, p := range packs {
		fmt.Fprintf(&imports, "\t_ %q\n", packPath+p)
	}
	// One offered locale leaves Locales nil: Serve installs the locale
	// middleware whenever Options.Locales is non-empty, and a one-locale
	// app must not grow /en/ prefixes and a switcher with one entry.
	localesDecl := "var Locales []string"
	if len(app.Locales) > 1 {
		localesDecl = "var Locales = " + literal(app.Locales)
	}
	src := fmt.Sprintf(goTemplate, imports.String(), app.DefaultLocale, localesDecl, literal(app.Locales))
	if goSrc, err = format.Source([]byte(src)); err != nil {
		return nil, nil, err
	}
	return goSrc, []byte(testTemplate), nil
}

func literal(codes []string) string {
	quoted := make([]string, len(codes))
	for i, c := range codes {
		quoted[i] = strconv.Quote(c)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

// Emit writes gen/locales/packs.go and packs_test.go for app and
// returns both paths. It returns every file it emitted, changed or not:
// generate removes generated files no emitter claims, so reporting only
// the changed ones would delete the unchanged ones on the next run.
func Emit(genDir string, app manifest.App) ([]string, error) {
	goSrc, testSrc, err := render(app)
	if err != nil {
		return nil, err
	}
	paths := Paths(genDir)
	for i, content := range [][]byte{goSrc, testSrc} {
		if err := writeFileIfChanged(paths[i], content); err != nil {
			return nil, err
		}
	}
	return paths, nil
}

// Paths are the files Emit writes, for generate --check to count as
// this run's output without writing them.
func Paths(genDir string) []string {
	dir := filepath.Join(genDir, "locales")
	return []string{filepath.Join(dir, goFile), filepath.Join(dir, testFile)}
}

// writeFileIfChanged leaves an unchanged file's mtime alone, so go's
// build cache and rastrillo dev's watcher do not see a change that is
// not one. A copy of internal/generate's, which is unexported there.
func writeFileIfChanged(path string, content []byte) error {
	if existing, err := os.ReadFile(path); err == nil && bytes.Equal(existing, content) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, content, 0o644)
}

// Stale compares gen/locales' packs files with what Emit would write
// for app, writing nothing. It returns "" when they match, else the
// Appendix C.2 op.doctor.packs_stale line, so generate --check and
// doctor report a stale file in the same words. A refused declaration
// is an error, as it is for Emit.
func Stale(genDir string, app manifest.App) (string, error) {
	goSrc, testSrc, err := render(app)
	if err != nil {
		return "", err
	}
	dir := filepath.Join(genDir, "locales")
	gotGo, errGo := os.ReadFile(filepath.Join(dir, goFile))
	gotTest, errTest := os.ReadFile(filepath.Join(dir, testFile))
	for _, err := range []error{errGo, errTest} {
		if err != nil && !os.IsNotExist(err) {
			return "", err
		}
	}
	if errGo == nil && errTest == nil && bytes.Equal(gotGo, goSrc) && bytes.Equal(gotTest, testSrc) {
		return "", nil
	}
	return fmt.Sprintf(staleMsg, app.Locales, generatedFor(gotGo)), nil
}

// generatedFor reads the offered list an existing packs.go was written
// for, so the stale message names both sides. A missing or hand-broken
// file yields nil: the message still says to regenerate.
func generatedFor(src []byte) []string {
	if src == nil {
		return nil
	}
	f, err := parser.ParseFile(token.NewFileSet(), goFile, src, 0)
	if err != nil {
		return nil
	}
	var out []string
	ast.Inspect(f, func(n ast.Node) bool {
		vs, ok := n.(*ast.ValueSpec)
		if !ok || len(vs.Names) != 1 || vs.Names[0].Name != "offered" || len(vs.Values) != 1 {
			return true
		}
		if lit, ok := vs.Values[0].(*ast.CompositeLit); ok {
			for _, e := range lit.Elts {
				if b, ok := e.(*ast.BasicLit); ok {
					if s, err := strconv.Unquote(b.Value); err == nil {
						out = append(out, s)
					}
				}
			}
		}
		return false
	})
	return out
}
