func TestEmitWritesDerivedPacks(t *testing.T) {
	gen := t.TempDir()
	if _, err := Emit(gen, manifest.App{Locales: []string{"en", "zh-Hans", "zh-Hant", "pt-PT", "yue"}, DefaultLocale: "en"}); err != nil {
		t.Fatal(err)
	}
	src, _ := os.ReadFile(filepath.Join(gen, "locales", "packs.go"))
	for _, p := range []string{"en", "pt", "yue", "zh"} {
		if !strings.Contains(string(src), `_ "amadan.net/rastrillo/rastrillo/locales/`+p+`"`) {
			t.Errorf("packs.go lacks pack %s:\n%s", p, src)
		}
	}
	if strings.Count(string(src), `_ "amadan.net`) != 4 {
		t.Errorf("packs.go imports something extra:\n%s", src)
	}
	if !strings.Contains(string(src), `var Locales = []string{"en", "zh-Hans", "zh-Hant", "pt-PT", "yue"}`) {
		t.Errorf("Locales not written as declared:\n%s", src)
	}
}

func TestEmitOneLocaleHasNoRouting(t *testing.T) {
	gen := t.TempDir()
	if _, err := Emit(gen, manifest.App{Locales: []string{"en"}, DefaultLocale: "en"}); err != nil {
		t.Fatal(err)
	}
	src, err := os.ReadFile(filepath.Join(gen, "locales", "packs.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(src), "var Locales []string\n") {
		t.Errorf("a one-locale app must leave Locales nil (no prefixes, no switcher):\n%s", src)
	}
}

func TestEmitRefusesBadCodes(t *testing.T) {
	for _, codes := range [][]string{{"en", "de--CH"}, {"en", "xx"}, {"en_US"}, {"en", "en"}} {
		if _, err := Emit(t.TempDir(), manifest.App{Locales: codes, DefaultLocale: codes[0]}); err == nil {
			t.Errorf("Emit(%v) accepted it", codes)
		}
	}
}

func TestStaleNamesBothSides(t *testing.T) {
	gen := t.TempDir()
	en := manifest.App{Locales: []string{"en"}, DefaultLocale: "en"}
	if msg, err := Stale(gen, en); err != nil || !strings.Contains(msg, "generated for []") {
		t.Errorf("no packs.go yet: %q, %v", msg, err)
	}
	paths, err := Emit(gen, en)
	if err != nil || len(paths) != 2 {
		t.Fatalf("Emit: %v, %v", paths, err)
	}
	if msg, err := Stale(gen, en); msg != "" || err != nil {
		t.Errorf("fresh output reported stale: %q, %v", msg, err)
	}
	// Unchanged output is still reported: a caller pruning files no
	// emitter claims would otherwise delete it.
	if again, _ := Emit(gen, en); len(again) != 2 {
		t.Errorf("a rerun with nothing to change returned %v", again)
	}
	msg, err := Stale(gen, manifest.App{Locales: []string{"en", "es"}, DefaultLocale: "en"})
	if err != nil || !strings.Contains(msg, "offers [en es] but gen/locales/packs.go was generated for [en]") {
		t.Errorf("stale: %q, %v", msg, err)
	}
}

// The file app authors read, byte for byte: its comments are approved
// copy (Appendix C.6), so a template edit that moves a word fails here.
func TestEmitExactOutput(t *testing.T) {
	gen := t.TempDir()
	if _, err := Emit(gen, manifest.App{Locales: []string{"en", "zh-TW"}, DefaultLocale: "en"}); err != nil {
		t.Fatal(err)
	}
	src, _ := os.ReadFile(filepath.Join(gen, "locales", "packs.go"))
	want := `// Code generated by rastrillo generate; DO NOT EDIT.

// Package locales links the formatting packs manifest/app.toml's
// locales need. Wire DefaultLocale and Locales into rastrillo.Options.
package locales

import (
	_ "amadan.net/rastrillo/rastrillo/locales/en"
	_ "amadan.net/rastrillo/rastrillo/locales/zh"
)

// DefaultLocale is manifest/app.toml's default_locale.
const DefaultLocale = "en"

// Locales is manifest/app.toml's locales. It is nil when the app
// offers one locale, so a one-locale app gets no /xx/ prefixes and no
// switcher.
var Locales = []string{"en", "zh-TW"}

var offered = []string{"en", "zh-TW"}
`
	if string(src) != want {
		t.Errorf("packs.go:\n%s\nwant:\n%s", src, want)
	}
}

func TestEmitRefusalsAreTheApprovedLines(t *testing.T) {
	for codes, want := range map[string]string{
		"en de--CH": `"de--CH" is not a well-formed language tag`,
		"en xx":     `offered locale "xx" is not a locale CLDR's modern set formats`,
		"en_US":     `"en_US" is not in canonical form; write "en-US"`,
		"en en":     `"en" is offered twice`,
	} {
		list := strings.Fields(codes)
		_, err := Emit(t.TempDir(), manifest.App{Locales: list, DefaultLocale: list[0]})
		if err == nil || err.Error() != want {
			t.Errorf("Emit(%v) = %v, want %s", list, err, want)
		}
	}
	_, err := Emit(t.TempDir(), manifest.App{Locales: []string{"en"}, DefaultLocale: "es"})
	if err == nil || err.Error() != `default locale "es" is not one of the offered locales [en]` {
		t.Errorf("default not offered: %v", err)
	}
}
