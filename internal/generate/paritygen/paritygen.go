// Package paritygen emits gen/paritytest: one scenario per exposed
// resource, run once through the page door and once through the API
// door, each against a fresh app, with the outcomes compared step by
// step. Matching route counts prove nothing about two doors; a page
// that reshapes its input before the operation, or a door that answers
// a refusal with the wrong kind, only shows when both are driven. The
// app supplies the Fixture (how to build it, sign in and mint a token)
// and calls one Run function per resource. The goldens under
// testdata/paritytest are the contract for what is emitted.
package paritygen

import (
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strings"

	"amadan.net/rastrillo/rastrillo"
	"amadan.net/rastrillo/rastrillo/currency"
	"amadan.net/rastrillo/rastrillo/form"
	"amadan.net/rastrillo/rastrillo/internal/generate/shape"
	"amadan.net/rastrillo/rastrillo/internal/wirename"
)

// header starts every file so prune can tell it from a hand-written one.
const header = "// Code generated by rastrillo generate. DO NOT EDIT.\n\n"

// changed is the update step's new text: one value no generated create
// value can equal, so a page door that ignored the update fails the
// row after it.
const changed = "Changed by parity"

// Emit writes gen/paritytest/fixture.go and one <name>_parity.go per
// exposed resource, and returns the paths, or nothing when no resource
// is exposed: a package with no Run function is one nothing calls. The
// suffix is not decoration: a file named after orders_test or
// orders_windows would be a test file or a Windows-only one, and its
// Run function would vanish from every other build. It also keeps a
// resource named fixture from replacing the helpers.
func Emit(genDir string, rs []rastrillo.Resource) ([]string, error) {
	var exposed []rastrillo.Resource
	for _, r := range rs {
		if r.Exposed() {
			exposed = append(exposed, r)
		}
	}
	if len(exposed) == 0 {
		return nil, nil
	}
	dir := filepath.Join(genDir, "paritytest")
	files := []struct{ path, src string }{{filepath.Join(dir, "fixture.go"), fixtureGo(exposed)}}
	for _, r := range exposed {
		src, err := resourceGo(r)
		if err != nil {
			return nil, err
		}
		files = append(files, struct{ path, src string }{filepath.Join(dir, r.Name+"_parity.go"), src})
	}
	var written []string
	for _, f := range files {
		formatted, err := format.Source([]byte(f.src))
		if err != nil {
			return nil, fmt.Errorf("paritytest/%s: %w\n%s", filepath.Base(f.path), err, f.src)
		}
		if err := shape.WriteFile(f.path, formatted); err != nil {
			return nil, fmt.Errorf("paritytest/%s: %w", filepath.Base(f.path), err)
		}
		written = append(written, f.path)
	}
	return written, nil
}

// edit is the update step: the form that edits the first text field,
// its route segment, and that form's group.
type edit struct {
	field  rastrillo.Field
	action string // "edit-basics"
	group  []rastrillo.Field
}

// editOf is r's update step: the first text field of the basics, or of
// the advanced fields when the basics are all money, since a changed
// amount would read differently in every locale. ok is false when no
// group has one, and the scenario then has no update.
func editOf(r rastrillo.Resource) (edit, bool) {
	for _, g := range []struct {
		action string
		fields []rastrillo.Field
	}{{"edit-basics", r.Form.Basics}, {"edit-advanced", r.Form.Advanced}} {
		for _, f := range g.fields {
			if f.Kind != rastrillo.Money {
				return edit{f, g.action, g.fields}, true
			}
		}
	}
	return edit{}, false
}

// required is r's required create fields by wire name, sorted as
// refused compares them.
func required(r rastrillo.Resource) []string {
	var out []string
	for _, f := range shape.FormFields(r) {
		if f.Required {
			out = append(out, wirename.Name(f.Name))
		}
	}
	sort.Strings(out)
	return out
}

// fixtureGo renders fixture.go. Each helper only some resources need is
// emitted only when one of rs does, because the examples' staticcheck
// fails on an unused function or import: money for a create with a
// money field, moneyForm for an edit form holding one, refused for a
// resource with a required field, hidden for a scoped one.
func fixtureGo(rs []rastrillo.Resource) string {
	var needMoney, needMoneyForm, needRefused, needHidden bool
	for _, r := range rs {
		needMoney = needMoney || len(shape.MoneyFields(shape.FormFields(r))) > 0
		if e, ok := editOf(r); ok {
			needMoneyForm = needMoneyForm || len(shape.MoneyFields(e.group)) > 0
		}
		needRefused = needRefused || len(required(r)) > 0
		needHidden = needHidden || shape.Scoped(r)
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(fixtureDoc)
	b.WriteString("import (\n\t\"bytes\"\n\t\"database/sql\"\n\t\"encoding/json\"\n")
	if needRefused {
		b.WriteString("\t\"fmt\"\n")
	}
	b.WriteString("\t\"io\"\n\t\"net/http\"\n\t\"net/http/httptest\"\n\t\"net/url\"\n\t\"path\"\n")
	if needRefused {
		b.WriteString("\t\"sort\"\n")
	}
	b.WriteString("\t\"strings\"\n\t\"testing\"\n")
	if needMoney || needMoneyForm {
		b.WriteString("\n")
		if needMoney {
			b.WriteString("\t\"amadan.net/rastrillo/rastrillo/currency\"\n")
		}
		if needMoneyForm {
			b.WriteString("\t\"amadan.net/rastrillo/rastrillo/form\"\n")
		}
		b.WriteString("\t_ \"amadan.net/rastrillo/rastrillo/locales/en\"\n")
	}
	b.WriteString(")\n\n")
	b.WriteString(fixtureBody)
	if needRefused {
		b.WriteString(fixtureRefused)
	}
	if needHidden {
		b.WriteString(fixtureHidden)
	}
	if needMoney {
		b.WriteString(fixtureMoney)
	}
	if needMoneyForm {
		b.WriteString(fixtureMoneyForm)
	}
	return b.String()
}

// typed is the generated create value for f: text the person could
// have typed, and for money an amount with one reading in English
// whatever the currency's decimals.
func typed(r rastrillo.Resource, f rastrillo.Field) (string, error) {
	if f.Kind != rastrillo.Money {
		return "Parity " + strings.ToLower(form.Humanize(f.Name)), nil
	}
	exp, err := currency.Exponent(r.Currency)
	if err != nil {
		return "", fmt.Errorf("resource %q: %w", r.Name, err)
	}
	if exp == 0 {
		return "13", nil
	}
	return "12.50", nil
}

// pageFields renders a form's url.Values entries, one line each: the
// field's value, and for money the locale and currency the money input
// posts beside it.
func pageFields(r rastrillo.Resource, fields []rastrillo.Field, value func(rastrillo.Field) string) string {
	var b strings.Builder
	for _, f := range fields {
		fmt.Fprintf(&b, "\t\t%q: {%s},\n", f.Name, value(f))
		if f.Kind == rastrillo.Money {
			fmt.Fprintf(&b, "\t\t%q: {\"en\"},\n\t\t%q: {%q},\n", f.Name+".locale", f.Name+".currency", r.Currency)
		}
	}
	return b.String()
}

// resourceGo renders r's Run function and its two halves.
func resourceGo(r rastrillo.Resource) (string, error) {
	plural := shape.PascalCase(r.Name)
	fn := shape.LowerFirst(plural)
	api := "/api/v1/" + r.Name
	fields := shape.FormFields(r)
	req := required(r)
	e, hasEdit := editOf(r)

	var defaults []string
	for _, f := range fields {
		v, err := typed(r, f)
		if err != nil {
			return "", err
		}
		defaults = append(defaults, fmt.Sprintf("%q: %q", f.Name, v))
	}
	fromValues := func(f rastrillo.Field) string { return fmt.Sprintf("values[%q]", f.Name) }

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package paritytest\n\nimport (\n\t\"fmt\"\n\t\"net/url\"\n\t\"testing\"\n)\n\n")
	fmt.Fprintf(&b, "// Run%[1]s runs the parity scenario for %[2]s.\nfunc Run%[1]s(t *testing.T, f Fixture) {\n", plural, r.Name)
	fmt.Fprintf(&b, "\tvalues := f.ValidCreate(%q)\n\tif values == nil {\n\t\tvalues = map[string]string{%s}\n\t}\n", r.Name, strings.Join(defaults, ", "))
	fmt.Fprintf(&b, "\tcompare(t, %[1]sPages(t, f, values), %[1]sAPI(t, f, values))\n}\n\n", fn)

	// The page door. Rows are read through the API in this app too, so
	// both halves compare the same JSON.
	fmt.Fprintf(&b, "func %sPages(t *testing.T, f Fixture, values map[string]string) []step {\n", fn)
	b.WriteString("\th, db := f.New(t)\n\tf.Prepare(t, db, \"a\")\n\ta := f.SignIn(t, h, db, \"a\")\n\ttoken := f.Token(t, db, \"a\")\n\tvar steps []step\n\n")
	fmt.Fprintf(&b, "\tcreated := page(t, a, \"POST\", %q, url.Values{\n%s\t})\n", r.Route, pageFields(r, fields, fromValues))
	b.WriteString("\tid := lastID(t, created)\n")
	b.WriteString("\tsteps = append(steps, step{\"create\", kind(created), \"\"})\n")
	fmt.Fprintf(&b, "\tsteps = append(steps, step{\"row after create\", \"ok\", row(t, h, token, %q+id)})\n\n", api+"/")
	if len(req) > 0 {
		var blank []string
		for _, f := range fields {
			blank = append(blank, fmt.Sprintf("%q: {\"\"}", f.Name))
			if f.Kind == rastrillo.Money {
				blank = append(blank, fmt.Sprintf("%q: {\"en\"}, %q: {%q}", f.Name+".locale", f.Name+".currency", r.Currency))
			}
		}
		fmt.Fprintf(&b, "\tsteps = append(steps, step{\"invalid create\", page(t, a, \"POST\", %q, url.Values{%s}), \"\"})\n\n", r.Route, strings.Join(blank, ", "))
	}
	if hasEdit {
		// An edit form posts its whole group, the others as they are
		// stored, as a browser does; the API's PATCH sends only the
		// changed field. Both must end at the same row.
		var others, money []rastrillo.Field
		for _, f := range e.group {
			switch {
			case f.Name == e.field.Name:
			case f.Kind == rastrillo.Money:
				money = append(money, f)
			default:
				others = append(others, f)
			}
		}
		if len(others)+len(money) > 0 {
			fmt.Fprintf(&b, "\tcur := record(t, h, token, %q+id)\n", api+"/")
		}
		fmt.Fprintf(&b, "\tedit := url.Values{\n\t\t%q: {%q},\n", e.field.Name, changed)
		for _, f := range others {
			fmt.Fprintf(&b, "\t\t%q: {fmt.Sprint(cur[%q])},\n", f.Name, wirename.Name(f.Name))
		}
		b.WriteString("\t}\n")
		for _, f := range money {
			fmt.Fprintf(&b, "\tmoneyForm(t, edit, %q, cur[%q])\n", f.Name, wirename.Name(f.Name))
		}
		fmt.Fprintf(&b, "\tsteps = append(steps, step{\"update\", kind(page(t, a, \"POST\", %q+id+%q, edit)), \"\"})\n", r.Route+"/", "/"+e.action)
		fmt.Fprintf(&b, "\tsteps = append(steps, step{\"row after update\", \"ok\", row(t, h, token, %q+id)})\n\n", api+"/")
	}
	if shape.Scoped(r) {
		// Asserted on each door as well as compared: two doors that
		// both show the row agree, and compare alone would pass them.
		b.WriteString("\tb := f.SignIn(t, h, db, \"b\")\n")
		fmt.Fprintf(&b, "\tother := page(t, b, \"GET\", %q+id, nil)\n", r.Route+"/")
		b.WriteString("\thidden(t, \"page\", other)\n")
		b.WriteString("\tsteps = append(steps, step{\"another person's row\", other, \"\"})\n\n")
	}
	fmt.Fprintf(&b, "\tsteps = append(steps, step{\"delete\", kind(page(t, a, \"POST\", %q+id+\"/delete\", url.Values{})), \"\"})\n", r.Route+"/")
	fmt.Fprintf(&b, "\tsteps = append(steps, step{\"row after delete\", page(t, a, \"GET\", %q+id, nil), \"\"})\n", r.Route+"/")
	fmt.Fprintf(&b, "\tsteps = append(steps, step{\"missing row\", page(t, a, \"GET\", %q, nil), \"\"})\n", r.Route+"/999999")
	b.WriteString("\treturn steps\n}\n\n")

	// The API door.
	fmt.Fprintf(&b, "func %sAPI(t *testing.T, f Fixture, values map[string]string) []step {\n", fn)
	b.WriteString("\th, db := f.New(t)\n\tf.Prepare(t, db, \"a\")\n\ttoken := f.Token(t, db, \"a\")\n\tvar steps []step\n\n")
	fmt.Fprintf(&b, "\tk, body := call(t, h, token, \"POST\", %q, map[string]any{\n", api)
	for _, f := range fields {
		if f.Kind == rastrillo.Money {
			fmt.Fprintf(&b, "\t\t%q: money(t, values[%q], %q),\n", wirename.Name(f.Name), f.Name, r.Currency)
		} else {
			fmt.Fprintf(&b, "\t\t%q: values[%q],\n", wirename.Name(f.Name), f.Name)
		}
	}
	b.WriteString("\t})\n\tid := fmt.Sprint(body[\"id\"])\n")
	b.WriteString("\tsteps = append(steps, step{\"create\", k, \"\"})\n")
	fmt.Fprintf(&b, "\tsteps = append(steps, step{\"row after create\", \"ok\", row(t, h, token, %q+id)})\n\n", api+"/")
	if len(req) > 0 {
		quoted := make([]string, len(req))
		for i, n := range req {
			quoted[i] = fmt.Sprintf("%q", n)
		}
		fmt.Fprintf(&b, "\tk, body = call(t, h, token, \"POST\", %q, map[string]any{})\n", api)
		fmt.Fprintf(&b, "\trefused(t, body, %s)\n", strings.Join(quoted, ", "))
		b.WriteString("\tsteps = append(steps, step{\"invalid create\", k, \"\"})\n\n")
	}
	if hasEdit {
		fmt.Fprintf(&b, "\tk, _ = call(t, h, token, \"PATCH\", %q+id, map[string]any{%q: %q})\n", api+"/", wirename.Name(e.field.Name), changed)
		b.WriteString("\tsteps = append(steps, step{\"update\", k, \"\"})\n")
		fmt.Fprintf(&b, "\tsteps = append(steps, step{\"row after update\", \"ok\", row(t, h, token, %q+id)})\n\n", api+"/")
	}
	if shape.Scoped(r) {
		b.WriteString("\tother := f.Token(t, db, \"b\")\n")
		fmt.Fprintf(&b, "\tk, _ = call(t, h, other, \"GET\", %q+id, nil)\n", api+"/")
		b.WriteString("\thidden(t, \"API\", k)\n")
		b.WriteString("\tsteps = append(steps, step{\"another person's row\", k, \"\"})\n\n")
	}
	fmt.Fprintf(&b, "\tk, _ = call(t, h, token, \"DELETE\", %q+id, nil)\n", api+"/")
	b.WriteString("\tsteps = append(steps, step{\"delete\", k, \"\"})\n")
	fmt.Fprintf(&b, "\tk, _ = call(t, h, token, \"GET\", %q+id, nil)\n", api+"/")
	b.WriteString("\tsteps = append(steps, step{\"row after delete\", k, \"\"})\n")
	fmt.Fprintf(&b, "\tk, _ = call(t, h, token, \"GET\", %q, nil)\n", api+"/999999")
	b.WriteString("\tsteps = append(steps, step{\"missing row\", k, \"\"})\n")
	b.WriteString("\treturn steps\n}\n")
	return b.String(), nil
}
