package generate

import (
	"fmt"
	"go/format"
	"path/filepath"
	"strings"

	"amadan.net/rastrillo/rastrillo"
)

// goFile is one generated Go file of a store.
type goFile struct {
	name   string
	source []byte
}

// writeGoFiles formats and writes each file into dir, returning their
// paths in the order given.
func writeGoFiles(dir string, files ...goFile) ([]string, error) {
	var paths []string
	for _, file := range files {
		path := filepath.Join(dir, file.name)
		formatted, err := format.Source(file.source)
		if err == nil {
			err = writeFileIfChanged(path, formatted)
		}
		if err != nil {
			return nil, fmt.Errorf("%s: %s: %w", filepath.Base(dir),
				file.name, err)
		}
		paths = append(paths, path)
	}
	return paths, nil
}

// declareGo renders gen/store/<name>/declare.go. It is its own file
// because a released migrations.go must regenerate byte for byte. A
// user-scoped table is personal and erased by its owner column, which
// holds the session subject; any other table is shared.
func declareGo(resource rastrillo.Resource) []byte {
	var out strings.Builder
	out.WriteString("// Code generated by rastrillo generate; DO NOT EDIT.\n")
	fmt.Fprintf(&out, "package %sstore\n\n", resource.Name)
	out.WriteString(
		"import \"amadan.net/rastrillo/rastrillo/migrate\"\n\n")
	out.WriteString("// Declaration says what this table holds. Declare " +
		"it on the set that\n// applies Migrations, where " +
		"audit.CheckSchema looks for it.\n")
	out.WriteString("var Declaration = migrate.Data{\n")
	fmt.Fprintf(&out, "Name: %q,\nKey: []string{\"id\"},\n", resource.Name)
	if !scoped(resource) {
		out.WriteString("Kind: migrate.Shared,\n}\n")
		return []byte(out.String())
	}
	out.WriteString("Kind: migrate.Personal,\n" +
		"Owner: migrate.Subject(\"owner\"),\n" +
		"Erase: migrate.EraseRow,\nExport: true,\n}\n")
	return []byte(out.String())
}
