func TestRegeneratingAnExistingTreeRemovesWhatNothingGenerates(t *testing.T) {
	app := scratchApp(t, map[string]string{ // the manifestgen_test.go scratch-module helper
		"manifest/a.toml": resourceTOML("a", "exclusive"),
		"manifest/b.toml": resourceTOML("b", "mergeable"),
	})
	mustGenerate(t, app)
	os.WriteFile(filepath.Join(app, "gen", "store", "b", "notes.md"), []byte("mine"), 0o644) // a hand file in gen/
	os.Remove(filepath.Join(app, "manifest", "b.toml"))
	mustGenerate(t, app)
	for _, gone := range []string{"gen/store/b/store.go", "gen/store/b/migrations.go", "gen/templates/b", "gen/actions/b"} {
		if _, err := os.Stat(filepath.Join(app, gone)); !os.IsNotExist(err) {
			t.Errorf("%s survived regeneration", gone)
		}
	}
	if _, err := os.Stat(filepath.Join(app, "gen", "store", "b", "notes.md")); err != nil {
		t.Errorf("a file without a generated header was removed: %v", err)
	}
	for _, kept := range []string{"gen/store/a/models.go", "gen/store/a/queries.sql.go", "gen/store/a/migrations.go"} {
		if _, err := os.Stat(filepath.Join(app, kept)); err != nil {
			t.Errorf("%s was removed though its store is still generated", kept)
		}
	}
}

// Review round two: a resource that changes from exclusive to
// mergeable keeps its store directory, but sqlc's files in it must go,
// or the package declares two Queries and two New and stops compiling.
func TestExclusiveToMergeableTransition(t *testing.T) {
	app := scratchApp(t, map[string]string{"manifest/a.toml": resourceTOML("a", "exclusive")})
	mustGenerate(t, app)
	for _, f := range []string{"db.go", "models.go", "queries.sql.go"} {
		if _, err := os.Stat(filepath.Join(app, "gen", "store", "a", f)); err != nil {
			t.Fatalf("exclusive store lacks sqlc's %s: %v", f, err)
		}
	}
	os.WriteFile(filepath.Join(app, "manifest", "a.toml"), []byte(resourceTOML("a", "mergeable")), 0o644)
	if err := checkGenerate(t, app); err == nil {
		t.Error("--check passed before regenerating the changed store")
	}
	mustGenerate(t, app)
	for _, f := range []string{"db.go", "models.go", "queries.sql.go", "schema.sql", "queries.sql"} {
		if _, err := os.Stat(filepath.Join(app, "gen", "store", "a", f)); !os.IsNotExist(err) {
			t.Errorf("%s survived the change to a mergeable store", f)
		}
	}
	if out, err := goBuild(app); err != nil {
		t.Errorf("the app does not compile after the transition:\n%s", out)
	}
	if err := checkGenerate(t, app); err != nil {
		t.Errorf("--check after regenerating: %v", err)
	}
}

func TestCheckReportsStaleGeneratedFiles(t *testing.T) {
	app := scratchApp(t, map[string]string{"manifest/a.toml": resourceTOML("a", "exclusive")})
	mustGenerate(t, app)
	stale := filepath.Join(app, "gen", "store", "old", "store.go")
	os.MkdirAll(filepath.Dir(stale), 0o755)
	os.WriteFile(stale, []byte("// Code generated by rastrillo generate; DO NOT EDIT.\npackage oldstore\n"), 0o644)
	if err := checkGenerate(t, app); err == nil || !strings.Contains(err.Error(), "gen/store/old/store.go") {
		t.Errorf("--check passed with a stale generated file: %v", err)
	}
}

// Review carry from Task 20: an app that ejects a generated action by
// copying it to actions/ keeps the generated header at the top, and
// Rewrite carries it into gen/. Pruning removes files with that header
// that nothing generated this run, so unless the rewritten copy counts
// as this run's, the next generate deletes the app's own action.
func TestHandActionWithACopiedHeaderSurvivesGenerate(t *testing.T) {
	app := scratchApp(t, map[string]string{"manifest/a.toml": resourceTOML("a", "exclusive")})
	mustGenerate(t, app)
	gen := filepath.Join(app, "gen", "actions", "a", "index_get", "index.GET.go")
	src, err := os.ReadFile(gen)
	if err != nil {
		t.Fatal(err)
	}
	header, rest, ok := strings.Cut(string(src), "\n\n")
	if !ok || !strings.HasPrefix(header, "// Code generated by rastrillo generate") {
		t.Fatalf("generated action has no header to copy:\n%s", src)
	}
	const mark = "// kept by hand"
	writeFile(t, app, "actions/a/index.GET.go", header+"\n\n//go:build "+BuildTag+"\n\n"+rest+"\n"+mark+"\n")
	for run := 1; run <= 2; run++ {
		mustGenerate(t, app)
		got, err := os.ReadFile(gen)
		if err != nil || !strings.Contains(string(got), mark) {
			t.Fatalf("after generate %d the hand action's copy is gone or not the hand file: %v\n%s", run, err, got)
		}
	}
	if out, err := goBuild(app); err != nil {
		t.Errorf("the app does not build with the hand action:\n%s", out)
	}
}

// A hand templates/<name>/<file>.html beside gen/ takes over that page:
// EmitTemplates skips the file and, on purpose, does not count the
// skipped path as written, so the copy an earlier run left inside gen/
// is what pruning removes. --check names it first, generate removes
// it, the hand file is untouched, and the app still builds. A copy
// inside gen/ without a generated header is the app's and stays.
func TestHandTemplateBesideGenPrunesTheGeneratedCopy(t *testing.T) {
	app := scratchApp(t, map[string]string{"manifest/a.toml": resourceTOML("a", "exclusive")})
	mustGenerate(t, app)
	gen := filepath.Join(app, "gen", "templates", "a", "list.html")
	src, err := os.ReadFile(gen)
	if err != nil {
		t.Fatal(err)
	}
	const mark = "<!-- the app's own list page -->"
	writeFile(t, app, "templates/a/list.html", string(src)+"\n"+mark+"\n")
	_, rest, _ := strings.Cut(string(src), "*/}}\n")
	writeFile(t, app, "gen/templates/a/list.copy.html", "<!-- a copy without the header -->\n"+rest)

	if err := checkGenerate(t, app); err == nil || !strings.Contains(err.Error(), "gen/templates/a/list.html") {
		t.Errorf("--check with a hand list.html beside gen/: %v; want it to name the generated copy as stale", err)
	}
	mustGenerate(t, app)
	if _, err := os.Stat(gen); !os.IsNotExist(err) {
		t.Errorf("gen/templates/a/list.html survived generate with a hand file owning the page: %v", err)
	}
	for _, kept := range []string{"templates/a/list.html", "gen/templates/a/list.copy.html", "gen/templates/a/show.html"} {
		if _, err := os.Stat(filepath.Join(app, kept)); err != nil {
			t.Errorf("%s was removed: %v", kept, err)
		}
	}
	if got, _ := os.ReadFile(filepath.Join(app, "templates", "a", "list.html")); !strings.Contains(string(got), mark) {
		t.Errorf("the hand file was rewritten:\n%s", got)
	}
	if err := checkGenerate(t, app); err != nil {
		t.Errorf("--check after generate: %v", err)
	}
	if out, err := goBuild(app); err != nil {
		t.Errorf("the app does not build with the hand template:\n%s", out)
	}
}
