func TestInspectFindsWhatTheCSPDrops(t *testing.T) {
	cases := []struct {
		name, file, source string
		line               int
		problem            string
	}{
		{"style attribute", "page.html",
			"<main>\n<div class=\"x\" style=\"color: red\">", 2, "style"},
		{"style attribute in a template branch", "page.html",
			`<p {{if .Hidden}}style="display:none"{{end}}>`, 1, "style"},
		{"style attribute with a templated value", "page.html",
			`<p style="{{.Colour}}">`, 1, "style"},
		{"style block", "page.gohtml",
			"<head>\n\n<style>p { color: red }</style>", 3, "<style>"},
		{"inline handler", "page.tmpl",
			`<button onclick="save()">Save</button>`, 1, "onclick"},
		{"inline script", "page.html",
			"<script>\nalert(1)\n</script>", 1, "inline <script>"},
		{"javascript URL", "page.html",
			`<a href=" JavaScript:void(0)">`, 1, "javascript:"},
		{"style attribute in a Go string", "render.go",
			"package x\n\nconst card = `\n<div style=\"x\">`\n", 4,
			"style"},
		{"handler in an interpreted Go string", "render.go",
			"package x\n\nvar b = \"<b onmouseover=\\\"x()\\\">\"\n", 3,
			"onmouseover"},
		{"fragment of a Go string", "render.go",
			"package x\n\nvar open = \"<span style=\\\"\" + colour\n", 3,
			"style"},
		{"setAttribute style in a script", "static/board.js",
			"const card = find()\ncard.setAttribute('style', x)\n", 2,
			`setAttribute("style")`},
		{"markup in a script string", "static/board.js",
			"list.innerHTML = `<li style=\"top: ${y}px\">`\n", 1,
			"style"},
		{"markup in a nested template literal", "static/list.js",
			"list.innerHTML = `<ul>${items.map(item =>\n" +
				"  `<li style=\"color:red\">${item}</li>`\n" +
				").join(\"\")}</ul>`\n",
			2, "style"},
		{"escaped quotes in a script string", "static/a.js",
			`box.innerHTML = "<a href=\"javascript:void(0)\">Open</a>"`,
			1, "javascript:"},
		{"setAttribute with a space before its call", "static/a.js",
			"el.setAttribute (\n  \"onclick\", \"save()\")\n", 2,
			`setAttribute("onclick")`},
		{"handler on a later line of its tag", "page.html",
			"<button\n  class=\"save\"\n  onclick=\"save()\">Save</button>",
			3, "onclick"},
		{"old JavaScript type", "page.html",
			`<script type="text/jscript">boot()</script>`, 1,
			"inline <script>"},
	}
	for _, test := range cases {
		t.Run(test.name, func(t *testing.T) {
			findings := Inspect(test.file, []byte(test.source))
			if len(findings) != 1 {
				t.Fatalf("want one finding, got %v", findings)
			}
			finding := findings[0]
			if finding.Line != test.line {
				t.Errorf("line %d, want %d", finding.Line, test.line)
			}
			if !strings.Contains(finding.Problem, test.problem) {
				t.Errorf("problem %q does not name %q",
					finding.Problem, test.problem)
			}
		})
	}
}

func TestInspectPassesWhatTheCSPAllows(t *testing.T) {
	cases := []struct{ name, file, source string }{
		{"script with src", "page.html",
			`<script defer src="{{path $ (asset "static/a.js")}}"></script>`},
		{"module script with src", "page.html",
			`<script type="module" src="/static/a.js"></script>`},
		{"JSON data block", "page.html",
			`<script type="application/json" id="d">{"a":1}</script>`},
		{"hashed import map", "page.html",
			`<script type="importmap">{"imports":{}}</script>`},
		{"attribute names that only contain the words", "page.html",
			`<div data-style="x" rst-onboard data-onclick="y">`},
		{"words in text and attribute values", "page.html",
			`<p title="style=bold">Set style="x" onclick=</p>`},
		{"template comment", "page.html",
			`{{/* never <p style="x"> here */}}<p>`},
		{"HTML comment", "page.html", `<!-- <p style="x"> --><p>`},
		{"template action that compares", "page.html",
			`<p {{if lt .A .B}}rst-danger{{end}}>`},
		{"Go comment", "render.go",
			"package x\n\n// Never write <p style=\"x\">.\nvar a = 1\n"},
		{"Go test file", "render_test.go",
			"package x\n\nvar want = `<p style=\"x\">`\n"},
		{"generated Go file", "templates_gen.go",
			"// Code generated by tmplc. DO NOT EDIT.\n\npackage x\n\n" +
				"var page = `<p style=\"x\">`\n"},
		{"pattern naming a tag it never writes", "scan.go",
			"package x\n\nvar tag = regexp.MustCompile(`(?i)<script\\b`)\n" +
				"var open = \"<style\"\n"},
		{"CSSOM in a script", "static/drag.js",
			"card.style.setProperty('--x', x)\ncard.classList.add('on')\n"},
		{"comparison in a script", "static/a.js",
			"for (let i = 0; i<n; i++) { a.onclick = f }\n"},
		{"comments in a script", "static/a.js",
			"// Don't use el.setAttribute(\"style\", \"color:red\").\n" +
				"/* or '<p style=\"x\">' */\nlet a = 1\n"},
		{"template comment in a Go string", "render.go",
			"package x\n\nconst page = `{{/* Old: <p style=\"x\"> */}}<p>`\n"},
		{"javascript: in a value that is not a URL", "page.html",
			`<input value="javascript:void(0)" data-x="javascript:1">`},
		{"script type that is not JavaScript", "page.html",
			`<script type="application/javascript+json">{}</script>`},
		{"Markdown", "README.md", `<p style="x">`},
		{"stylesheet", "static/app.css", `p { color: red }`},
	}
	for _, test := range cases {
		t.Run(test.name, func(t *testing.T) {
			findings := Inspect(test.file, []byte(test.source))
			if len(findings) != 0 {
				t.Errorf("want none, got %v", findings)
			}
		})
	}
}

func TestFindWalksTheAppNotItsVendoredOrHiddenFiles(t *testing.T) {
	root := t.TempDir()
	write := func(path, source string) {
		t.Helper()
		full := filepath.Join(root, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(source), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module app\n")
	write("internal/app/templates/index.html", `<p style="x">`)
	write("internal/app/static/fiesta.js", `el.setAttribute("style", x)`)
	write("internal/app/testdata/bad.html", `<p style="x">`)
	write(".design-system/index.html", `<p style="x">`)
	write("tools/go.mod", "module tools\n")
	write("tools/page.html", `<p style="x">`)
	// A file it would not read anyway is not opened, so a broken one
	// cannot fail the check.
	broken := filepath.Join(root, "uploads", "photo.png")
	if err := os.MkdirAll(filepath.Dir(broken), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("missing.png", broken); err != nil {
		t.Fatal(err)
	}

	findings, err := Find(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 1 {
		t.Fatalf("want the one app template, got %v", findings)
	}
	want := "internal/app/templates/index.html:1: "
	if got := findings[0].String(); !strings.HasPrefix(got, want) {
		t.Errorf("got %q, want it to start %q", got, want)
	}
}
