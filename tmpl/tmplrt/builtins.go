// param is what a builtin declared with a reflect.Value parameter
// receives for v. text/template passes a value whose own type is
// reflect.Value as the reflect.Value it holds, and any other value as
// itself.
func param(v reflect.Value) reflect.Value {
	if v.IsValid() && v.Type() == reflectValueType && v.CanInterface() {
		return v.Interface().(reflect.Value)
	}
	return v
}

func params(vs []reflect.Value) []reflect.Value {
	out := make([]reflect.Value, len(vs))
	for i, v := range vs {
		out[i] = param(v)
	}
	return out
}

// Not is the builtin not: the negation of Truth.
func Not(arg reflect.Value) bool {
	return !truth(param(arg))
}

// Index is the builtin index: index x 1 2 3 is x[1][2][3].
func Index(item reflect.Value, indexes ...reflect.Value) (v reflect.Value, err error) {
	defer Catch(&err)
	return index(param(item), params(indexes)...)
}

// Slice is the builtin slice: slice x 1 2 is x[1:2].
func Slice(item reflect.Value, indexes ...reflect.Value) (v reflect.Value, err error) {
	defer Catch(&err)
	return slice(param(item), params(indexes)...)
}

// Len is the builtin len.
func Len(item reflect.Value) (n int, err error) {
	defer Catch(&err)
	return length(param(item))
}

// CallBuiltin is the builtin call. name is how the template wrote the
// function, for errors: text/template passes it as call's first
// argument.
func CallBuiltin(name string, fn reflect.Value, args ...reflect.Value) (v reflect.Value, err error) {
	defer Catch(&err)
	return call(name, param(fn), params(args)...)
}

// Eq is the builtin eq: arg1 == arg2[0] || arg1 == arg2[1] ...
func Eq(arg1 reflect.Value, arg2 ...reflect.Value) (b bool, err error) {
	defer Catch(&err)
	return eq(param(arg1), params(arg2)...)
}

